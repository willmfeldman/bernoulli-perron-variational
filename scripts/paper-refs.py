def build_snapshot(cfg: Config, key: str, aux: list[str], tex: list[str], version: str | None = None,
                   draft: bool | None = None) -> tuple[dict, list[Problem]]:
    paper = cfg.papers[key]
    version = str(paper["version"]) if version is None else version
    draft = bool(paper.get("draft", False)) if draft is None else draft
    probs: list[Problem] = []
    snap_rel = os.path.relpath(cfg.snapshot_path(key), cfg.root)
    entries, digest = read_aux_tree(aux)
    tex_info, envs = scan_tex(tex) if tex else ({}, {})
    prefixes = paper.get("prefixes") or {}
    raw: dict[str, list[str]] = {}
    cref: dict[str, str] = {}
    counts: dict[str, int] = {}
    for name, fields in entries:
        if name.endswith("@cref"):
            t = parse_cref_type(fields[0]) if fields else None
            if t:
                cref[name[: -len("@cref")]] = t
            continue
        if not fields or name.startswith(("sub@", "[", "tocindent")) or "@" in name:
            continue
        counts[name] = counts.get(name, 0) + 1
        raw[name] = fields  # LaTeX keeps the last definition
    labels: dict[str, dict] = {}
    for name in sorted(raw):
        f = raw[name]
        number = clean_number(f[0])
        if number is None:
            probs.append(Problem(snap_rel, 0, "error", "unresolved-macro",
                                 f"label {name!r}: number field {f[0]!r} contains an unexpanded macro"))
            number = clean_tex(f[0])
        anchor = f[3].strip() if len(f) > 3 else ""
        title = clean_tex(f[2]) if len(f) > 2 else ""
        kind, src, parent = None, "", None
        if name in cref:
            t = cref[name]
            kind, src = canon_kind(envs.get(t, t)), "cref"
        ti = tex_info.get(name)
        if kind is None and ti and ti["kind"]:
            kind, src = ti["kind"], "tex"
        if ti:
            parent = ti.get("parent")
        pk = None
        for pre in sorted(prefixes, key=len, reverse=True):
            if name.startswith(pre):
                pk = canon_kind(prefixes[pre])
                break
        if kind is None and pk:
            kind, src = pk, "prefix"
        counter = anchor.split(".", 1)[0] if anchor else ""
        if kind is None and counter in _ANCHOR_KINDS:
            kind, src = _ANCHOR_KINDS[counter], "anchor"
        if kind == "section" and counter == "appendix":
            kind = "appendix"
        if pk and kind and src in ("cref", "tex") and pk != kind and kind not in STRUCTURAL_KINDS:
            probs.append(Problem(snap_rel, 0, "warning", "prefix-kind",
                                 f"label {name!r} has prefix kind {pk} but is a {kind} ({number})"))
        if not number:
            probs.append(Problem(snap_rel, 0, "warning", "empty-number", f"label {name!r} has no number"))
        if not re.fullmatch(LABEL_CHARS, name) or "-/" in name:
            probs.append(Problem(snap_rel, 0, "warning", "uncitable",
                                 f"label {name!r} contains characters the link syntax cannot carry"))
        e = {"number": number, "kind": kind, "kind_from": src}
        if anchor:
            e["anchor"] = anchor
        if title and kind not in ("equation", "item"):  # hyperref puts the section title there
            e["title"] = title
        if parent and kind == "item":
            e["parent"] = parent
        if ti and ti.get("alias_of") and raw.get(ti["alias_of"], [None])[0] == f[0]:
            e["alias_of"] = ti["alias_of"]
        labels[name] = e
    dups = sorted(n for n, c in counts.items() if c > 1)
    snap = {
        "format": SNAPSHOT_FORMAT,
        "generator": f"{TOOL} {TOOL_VERSION}",
        "paper": key,
        "title": paper.get("title", ""),
        "arxiv": paper.get("arxiv", ""),
        "version": version,
        "draft": draft,
        "source": {
            "aux": sorted(os.path.basename(a) for a in aux),
            "aux_sha256": digest,
            "tex": sorted(os.path.basename(t) for t in tex),
            "tex_sha256": tex_digest(tex),
        },
        "duplicates": dups,
        "labels": labels,
    }
    return snap, probs


def tex_digest(tex: list[str]) -> str:
    """Hash of every .tex file read (with its \\input/\\include files)."""
    h = hashlib.sha256()
    for t in tex:
        h.update(load_tex(t).encode())
    return h.hexdigest()


def dump_snapshot(snap: dict) -> str:
    return json.dumps(snap, indent=1, sort_keys=True, ensure_ascii=False) + "\n"


def load_snapshot(cfg: Config, key: str) -> dict | None:
    path = cfg.snapshot_path(key)
    if not os.path.exists(path):
        return None
    try:
        snap = json.loads(read_text(path))
    except json.JSONDecodeError as e:
        die(f"{os.path.relpath(path, cfg.root)}: {e}")
    if snap.get("format") != SNAPSHOT_FORMAT or "labels" not in snap:
        die(f"{os.path.relpath(path, cfg.root)}: not a format-{SNAPSHOT_FORMAT} snapshot")
    return snap


def load_all_snapshots(cfg: Config, probs: list[Problem]) -> dict[str, dict]:
    snaps = {}
    for key in cfg.papers:
        s = load_snapshot(cfg, key)
        rel = os.path.relpath(cfg.snapshot_path(key), cfg.root)
        if s is None:
            probs.append(Problem(rel, 0, "error", "no-snapshot", f"missing; run `{TOOL}.py snapshot {key}`"))
            continue
        if s.get("paper") != key:
            probs.append(Problem(rel, 0, "error", "snapshot-key", f"snapshot is for {s.get('paper')!r}"))
        if str(s.get("version")) != str(cfg.papers[key]["version"]):
            probs.append(Problem(rel, 0, "error", "snapshot-version",
                                 f"snapshot version {s.get('version')!r} != config version "
                                 f"{cfg.papers[key]['version']!r}; re-run snapshot"))
        if bool(s.get("draft", False)) != bool(cfg.papers[key].get("draft", False)):
            probs.append(Problem(rel, 0, "error", "snapshot-draft", "snapshot draft flag differs from config"))
        for d in s.get("duplicates", []):
            probs.append(Problem(rel, 0, "error", "duplicate-label", f"label {d!r} is multiply defined in the paper"))
        snaps[key] = s
    probs += config_problems(cfg, snaps)
    return snaps


def load_references(cfg: Config, probs: list[Problem]) -> dict[str, dict[str, dict]]:
    """{paper key: {version: snapshot}}: the main snapshot plus the configured reference snapshots
    of other versions (``papers.KEY.references``), used by bootstrap to resolve each citation in
    the version it follows and to detect citations whose number means different things."""
    out: dict[str, dict[str, dict]] = {}
    for key in cfg.papers:
        vs: dict[str, dict] = {}
        main = load_snapshot(cfg, key)
        if main is not None:
            vs[str(main["version"])] = main
        for ver, path in cfg.reference_paths(key).items():
            rel = os.path.relpath(path, cfg.root)
            if not os.path.exists(path):
                probs.append(Problem(rel, 0, "error", "no-snapshot",
                                     f"reference snapshot for {key} {ver} missing; run `snapshot {key} --out {rel} "
                                     f"--as-version {ver} --frozen <tag>`"))
                continue
            snap = json.loads(read_text(path))
            if snap.get("paper") != key or str(snap.get("version")) != ver:
                probs.append(Problem(rel, 0, "error", "snapshot-version",
                                     f"reference snapshot is {snap.get('paper')} {snap.get('version')}, "
                                     f"config says {key} {ver}"))
                continue
            if ver in vs:
                probs.append(Problem(rel, 0, "error", "snapshot-version",
                                     f"reference {ver} duplicates the main snapshot version"))
                continue
            vs[ver] = snap
        out[key] = vs
    return out


def preflight(cfg: Config) -> tuple[dict[str, dict], list[Problem]]:
    """Snapshots plus every snapshot, config and identity error. Write commands stop on any error."""
    probs: list[Problem] = []
    snaps = load_all_snapshots(cfg, probs)
    cites = cited_labels(cfg)
    for key, snap in snaps.items():
        probs += identity_problems(cfg, key, snap, cites.get(key, {}),
                                   os.path.relpath(cfg.snapshot_path(key), cfg.root))
    return snaps, probs


# --------------------------------------------------------------------------- Lean comment regions


def comment_regions(text: str) -> list[tuple[int, int, str]]:
    """(start, end, kind) of comment bodies; kind is 'line' or 'block'."""
    out = []
    i, n = 0, len(text)
    ident = re.compile(r"[\w.'!?₀-₉ₐ-ₜᵢ-ᵪⱼ]")
    while i < n:
        c = text[i]
        if c == "-" and text.startswith("--", i):
            j = text.find("\n", i)
            j = n if j < 0 else j
            out.append((i + 2, j, "line"))
            i = j
        elif c == "/" and text.startswith("/-", i):
            depth, j = 1, i + 2
            while j < n and depth:
                if text.startswith("/-", j):
                    depth += 1
                    j += 2
                elif text.startswith("-/", j):
                    depth -= 1
                    j += 2
                else:
                    j += 1
            out.append((i + 2, j - 2 if depth == 0 else n, "block"))
            i = j
        elif c == '"':
            j = i + 1
            while j < n and text[j] != '"':
                j += 2 if text[j] == "\\" else 1
            i = j + 1
        elif c == "r" and (i == 0 or not ident.match(text[i - 1])):
            m = re.match(r'r(#*)"', text[i:])
            if m:
                close = '"' + m.group(1)
                j = text.find(close, i + m.end())
                i = n if j < 0 else j + len(close)
            else:
                i += 1
        elif c == "'" and (i == 0 or not ident.match(text[i - 1])):
            m = re.match(r"'(?:\\(?:x[0-9a-fA-F]{2}|u\{[0-9a-fA-F]+\}|.)|[^\\'\n])'", text[i:])
            i += m.end() if m else 1
        else:
            i += 1
    return out


def file_regions(rel: str, text: str) -> list[tuple[int, int, str]]:
    """Comment bodies to read. A Markdown code fence written as consecutive ``--`` lines
    (``-- ```lean`` ... ``-- ````) is an example: those lines are dropped."""
    if not rel.endswith(".lean"):
        return [(0, len(text), "md")]
    out, fence, last_line = [], None, -2
    for a, b, k in comment_regions(text):
        if k != "line":
            out.append((a, b, k))
            continue
        ln = line_of(text, a)
        if ln != last_line + 1 or text[text.rfind("\n", 0, a) + 1:a - 2].strip():
            fence = None  # a code line, a gap, or a trailing comment ends the run of comment lines
        last_line = ln
        body = text[a:b].strip()
        m = re.match(r"(```+|~~~+)", body)
        if fence is None and m:
            fence = m.group(1)[:3]
            continue
        if fence is not None:
            if body.startswith(fence):
                fence = None
            continue
        out.append((a, b, k))
    return out


# --------------------------------------------------------------------------- references


class Ref:
    __slots__ = ("start", "end", "text", "key", "label", "tstart")

    def __init__(self, m: re.Match, base: int):
        self.start, self.end = base + m.start(), base + m.end()
        self.tstart = base + m.start("text")
        self.text, self.key, self.label = m.group("text"), m.group("key"), m.group("label")


CODE_RES = (re.compile(r"^[ \t]*(```|~~~).*?^[ \t]*\1", re.M | re.S), re.compile(r"``[^`\n]*``|`[^`\n]*`"))


def code_spans(seg: str) -> list[tuple[int, int]]:
    """Fenced code blocks and inline code spans of a Markdown text: citations there are examples."""
    spans = [(m.start(), m.end()) for m in CODE_RES[0].finditer(seg)]
    for m in CODE_RES[1].finditer(seg):
        if not any(a <= m.start() < b for a, b in spans):
            spans.append((m.start(), m.end()))
    return spans


def find_refs(text: str, regions) -> list[Ref]:
    refs = []
    for a, b, _ in regions:
        seg = text[a:b]
        code = code_spans(seg)
        for m in REF_RE.finditer(seg):
            if "\n\n" in m.group("text") or re.search(r"\n[ \t]*\n", m.group("text")):
                continue
            if any(x <= m.start() < y for x, y in code):
                continue
            refs.append(Ref(m, a))
    return refs


def expected_for(label: str, snap: dict) -> dict | None:
    e = snap["labels"].get(label)
    if e is None:
        return None
    if e.get("kind") == "item":
        parent = snap["labels"].get(e.get("parent") or "")
        if parent:
            return {"kind": parent.get("kind"), "num": parent["number"], "item": e["number"]}
        return {"kind": None, "num": None, "item": e["number"]}
    return {"kind": e.get("kind"), "num": e["number"], "item": None}


def link_form(text: str) -> str:
    """'kw' (kind word + number at the start), 'num' (number only), 'item' (item only) or 'free'."""
    ms = list(LINK_KW_NUM_RE.finditer(text))
    nums = re.findall(rf"(?<![\w.]){NUM_EQ}", text)
    if len(ms) == 1 and re.fullmatch(r"[\s(*_]*", text[: ms[0].start()]) and len(nums) == 1:
        return "kw"
    m = LINK_NUM_ONLY_RE.match(text)
    if not ms and m and not re.search(r"[A-Za-z]{2,}", m.group("rest")) and len(nums) == 1:
        return "num"
    if not ms and ITEM_ONLY_RE.match(text):
        return "item"
    return "free"


def fix_link_text(text: str, exp: dict) -> tuple[str, list[str], list[str]]:
    """Return (new link text, what changed, problems sync cannot fix). Only the citation at the
    start of the link text is managed; text with any other shape is free text, left alone."""
    changes: list[str] = []
    flags: list[str] = []
    form = link_form(text)
    if form == "free":
        return text, changes, flags
    if exp["num"] is None:  # item without known parent: only the item is checked
        m = ITEM_ONLY_RE.match(text) or ITEM_AT_START_RE.search(text)
        if m and item_core(m.group("item")) != item_core(exp["item"]):
            new = text[: m.start("item")] + item_core(exp["item"]) + text[m.end("item"):]
            changes.append(f"item ({m.group('item')}) -> {exp['item']}")
            return new, changes, flags
        return text, changes, flags
    m = LINK_KW_NUM_RE.search(text) if form == "kw" else None
    if m:
        kw, num = m.group("kw"), m.group("num")
        out = text
        rest_at = m.end()
        # item suffix, if the label is an enumerate item
        if exp["item"] is not None:
            mi = ITEM_AT_START_RE.match(text[m.end():])
            want = "(" + item_core(exp["item"]) + ")"
            if mi is None:
                out = out[:rest_at] + want + out[rest_at:]
                changes.append(f"add item {want}")
            elif item_core(mi.group("item")) != item_core(exp["item"]):
                s, e = rest_at + mi.start("item"), rest_at + mi.end("item")
                out = out[:s] + item_core(exp["item"]) + out[e:]
                changes.append(f"item ({mi.group('item')}) -> {want}")
        if num != exp["num"]:
            out = out[: m.start("num")] + exp["num"] + out[m.end("num"):]
            changes.append(f"number {num} -> {exp['num']}")
        wk = word_kind(kw)
        if wk and exp["kind"] and not kind_compatible(wk, exp["kind"]):
            newkw = kind_display(exp["kind"], kw)
            out = out[: m.start("kw")] + newkw + out[m.end("kw"):]
            changes.append(f"kind {kw} -> {newkw}")
        return out, changes, flags
    if form == "item":
        mo = ITEM_ONLY_RE.match(text)
        if exp["item"] is None:
            flags.append(f"shows only an item {text.strip()!r} but the label is not an enumerate item")
        elif item_core(mo.group("item")) != item_core(exp["item"]):
            out = text[: mo.start("item")] + item_core(exp["item"]) + text[mo.end("item"):]
            return out, [f"item ({mo.group('item')}) -> ({item_core(exp['item'])})"], flags
        return text, [], flags
    m = LINK_NUM_ONLY_RE.match(text)
    out = text
    if exp["item"] is not None:
        mi = ITEM_AT_START_RE.match(m.group("rest"))
        if mi is None:
            flags.append(f"number-only link to an item label without the item suffix "
                         f"(want {exp['num']}({item_core(exp['item'])}))")
        elif item_core(mi.group("item")) != item_core(exp["item"]):
            s = m.start("rest") + mi.start("item")
            e = m.start("rest") + mi.end("item")
            out = out[:s] + item_core(exp["item"]) + out[e:]
            changes.append(f"item -> ({item_core(exp['item'])})")
    if m.group("num") != exp["num"]:
        out = out[: m.start("num")] + exp["num"] + out[m.end("num"):]
        changes.append(f"number {m.group('num')} -> {exp['num']}")
    return out, changes, flags


# --------------------------------------------------------------------------- line wrapping

MD_LINE_START = re.compile(r"^(?:[-+*>#|=]|\d+[.)](?:\s|$)|```|~~~|-/)")


def _protected_spans(line: str) -> list[tuple[int, int]]:
    spans = []
    for rx in (r"\]\([^)\s]*\)", r"`[^`]*`", r"\$[^$]*\$"):
        spans += [(m.start(), m.end()) for m in re.finditer(rx, line)]
    return spans


def _link_spans(line: str) -> list[tuple[int, int]]:
    return [(m.start(), m.end()) for m in REF_RE.finditer(line)]


def wrap_line(line: str, kind: str, limit: int, next_line: str | None) -> list[str] | None:
    """Split an over-long comment line at spaces. None if no safe split exists."""
    if len(line) <= limit or LINE_LIMIT_SKIP in line:
        return [line]
    body = line.lstrip()
    indent = line[: len(line) - len(body)]
    if kind == "line":
        ci = line.find("--")
        cont = " " * (len(line[:ci]) - len(line[:ci].lstrip()) if line[:ci].strip() else ci) + "-- "
        cont = indent + "-- " if not line[:ci].strip() else cont
        floor = ci + 3
    else:
        stripped = re.sub(r"^(/--|/-!|/-)\s*", "", body)
        if stripped.startswith(("#", "|")):
            return None
        if body.startswith(("/--", "/-!", "/-")):
            cont = (re.match(r"\s*", next_line).group(0) if next_line and next_line.strip() else indent)
        else:
            cont = indent
        lm = re.match(r"(\s*)([-*+]|\d+[.)])\s+", stripped if body.startswith("/-") else body)
        if lm:
            cont = cont + " " * (len(lm.group(2)) + 1)
        floor = len(indent) + (3 if body.startswith("/-") else 0) + 1
    prot = _protected_spans(line)
    links = _link_spans(line)

    def ok(p: int) -> bool:
        if p <= floor or line[p] != " ":
            return False
        if any(a < p < b for a, b in prot + links):  # a link is never split
            return False
        head, tail = line[:p].rstrip(), line[p:].lstrip()
        if not tail or len(head) > limit or MD_LINE_START.match(tail):
            return False
        return True

    for p in range(min(len(line) - 1, limit), floor, -1):
        if ok(p):
            head, tail = line[:p].rstrip(), cont + line[p:].lstrip()
            rest = wrap_line(tail, "line" if kind == "line" else "block_cont", limit, None)
            if rest is None:
                return [head, tail]
            return [head] + rest
    return None


