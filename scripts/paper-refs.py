def cmd_report(cfg: Config, args) -> int:
    probs: list[Problem] = []
    snaps = load_all_snapshots(cfg, probs)
    cites: dict[tuple[str, str], list[str]] = {}
    for rel in iter_files(cfg):
        text = read_text(os.path.join(cfg.root, rel))
        for r in find_refs(text, file_regions(rel, text)):
            cites.setdefault((r.key, r.label), []).append(f"{rel}:{line_of(text, r.start)}")
    out_json = {}
    lines = []
    for key in sorted(snaps):
        snap = snaps[key]
        labels = snap["labels"]
        direct = {lbl: v for (k, lbl), v in cites.items() if k == key}
        via_item: dict[str, list[str]] = {}
        aliases: dict[str, list[str]] = {}
        for name, e in labels.items():
            if e.get("alias_of") in labels:
                aliases.setdefault(e["alias_of"], []).append(name)
        for lbl, v in direct.items():
            e = labels.get(lbl)
            if e and e.get("kind") == "item" and e.get("parent"):
                via_item.setdefault(e["parent"], []).extend(v)
            if e and e.get("alias_of") in labels:  # count an alias with its primary label
                via_item.setdefault(e["alias_of"], []).extend(v)

        def wanted(e):
            if args.all:
                return True
            return e.get("kind") not in STRUCTURAL_KINDS

        def sort_key(item):
            name, e = item
            parts = re.split(r"[.]", e["number"])
            return ([(0, int(p)) if p.isdigit() else (1, p) for p in parts], name)

        rows = []
        for name, e in sorted(labels.items(), key=sort_key):
            if not wanted(e) or e.get("alias_of") in labels:
                continue
            locs = sorted(set(direct.get(name, []) + via_item.get(name, [])))
            files = sorted({l.rsplit(":", 1)[0] for l in locs})
            rows.append({"label": name, "aliases": sorted(aliases.get(name, [])),
                         "kind": e.get("kind"), "number": e["number"],
                         "title": e.get("title", ""), "count": len(locs), "files": files})
        unknown = sorted(lbl for lbl in direct if lbl not in labels)
        cited = sum(1 for r in rows if r["count"])
        ver = f"arXiv:{snap['arxiv']}{snap['version']}" if snap.get("arxiv") else snap["version"]
        out_json[key] = {"version": ver, "rows": rows, "unknown": unknown}
        lines.append(f"## {key}: {snap.get('title') or key} ({ver}{', draft' if snap.get('draft') else ''})")
        lines.append("")
        lines.append(f"{cited} of {len(rows)} {'labels' if args.all else 'numbered results'} cited.")
        lines.append("")
        lines.append("| Result | Label | Citations | Files |")
        lines.append("|---|---|---:|---|")
        for r in rows:
            disp = f"{kind_display(r['kind']) if r['kind'] else '?'} {r['number']}"
            if r["kind"] == "equation":
                disp = f"({r['number']})"
            fl = ", ".join(f"`{f}`" for f in r["files"][:3]) + (f" (+{len(r['files']) - 3})" if len(r["files"]) > 3 else "")
            al = "".join(f", `{a}`" for a in r["aliases"])
            lines.append(f"| {disp} | `{r['label']}`{al} | {r['count']} | {fl or '—'} |")
        if unknown:
            lines.append("")
            lines.append("Cited labels missing from this version: " + ", ".join(f"`{u}`" for u in unknown))
        lines.append("")
    if args.json:
        print(json.dumps(out_json, indent=1, sort_keys=True, ensure_ascii=False))
    else:
        print("\n".join(lines).rstrip())
    emit(probs)
    return 0


