_STOP_NAMES = {
    "Lean", "Mathlib", "Step", "Steps", "Part", "Case", "Cases", "The", "This", "That", "These", "Our",
    "Its", "In", "By", "See", "Here", "Then", "Hence", "Thus", "Also", "Moreover", "However", "Indeed",
    "Similarly", "Finally", "First", "Second", "Third", "Now", "Note", "So", "As", "For", "With", "And",
    "Proof", "Claim", "Main", "Statement", "Statements", "Challenge", "Solution", "Vocabulary", "Here",
}


def _mask(seg: str) -> str:
    """Blank out existing links, code spans, math spans and fenced code in a comment body."""
    chars = list(seg)

    def blank(a, b):
        for k in range(a, b):
            if chars[k] != "\n":
                chars[k] = " "

    for rx in (r"```.*?```", r"\[[^\[\]]*\]\([^)]*\)", r"`[^`\n]*`", r"\$[^$\n]*\$", r"https?://\S+"):
        for m in re.finditer(rx, seg, re.S):
            blank(m.start(), m.end())
    return "".join(chars)


def _word_in(word: str, text: str) -> bool:
    return re.search(rf"(?<![\w]){re.escape(word)}(?![\w])", text) is not None


def _context(seg: str, start: int, end: int, paper: dict, external: list[str]) -> tuple[str, str]:
    """('confirmed'|'external'|'plain'|'conflict', reason) for a citation at seg[start:end].
    A bracket citation ``[KEY, ...]`` is decisive. Any other verdict that the same sentence
    contradicts (an alias of this paper and a configured external name) is a conflict."""
    aliases = [a for a in paper.get("aliases", []) if a]
    if paper.get("arxiv"):
        aliases.append(str(paper["arxiv"]))
    verdict, why, rule = _context_rules(seg, start, end, aliases, external)
    if rule == "bracket":
        return verdict, why
    b, a = _sentence_parts(seg, start, end)
    sentence = b + " " + a
    ext_hit = [x for x in external if _word_in(x, sentence)]
    alias_hit = [a for a in aliases if _word_in(a, sentence)]
    if verdict == "confirmed" and ext_hit:
        return "conflict", f"{why}, but {ext_hit[0]!r} is in the same sentence"
    if verdict == "external" and alias_hit:
        return "conflict", f"{why}, but {alias_hit[0]!r} is in the same sentence"
    return verdict, why


def _context_rules(seg: str, start: int, end: int, aliases: list[str], external: list[str]
                   ) -> tuple[str, str, str]:
    before = seg[max(0, start - 160):start]
    after = seg[end:end + 90]
    sent_start = max(before.rfind(". "), before.rfind("\n\n"), before.rfind(";"))
    sentence = before[sent_start + 1:] if sent_start >= 0 else before
    lb = before.rfind("[")
    if lb >= 0 and "]" not in before[lb:]:
        m = re.match(r"\s*([A-Za-z][\w.'’\-– &+]*?)\s*,", before[lb + 1:])
        if m and not re.fullmatch(r"[A-Za-z]", m.group(1).strip()):
            key = m.group(1).strip()
            if any(a == key or a in key for a in aliases):
                return "confirmed", f"[{key}, ...]", "bracket"
            return "external", f"[{key}, ...]", "bracket"
    m = re.match(r"\s*(?:\((?:[ivx]+|[a-h])\))?\s*,?\s*(?:in|of|from)\s+(.{0,60})", after, re.S)
    if m:
        tgt = m.group(1)
        if any(a in tgt[:40] for a in aliases):
            return "confirmed", "followed by a citation of this paper", "rule"
        if any(x in tgt[:40] for x in external):
            return "external", f"followed by {tgt[:30].strip()!r}", "rule"
        if tgt.startswith("["):
            return "external", f"followed by {tgt[:20].strip()!r}", "rule"
        w = re.match(r"([A-Z][\w'’\-–]*\.?)", tgt)
        if w and w.group(1).rstrip(".") not in _STOP_NAMES and not word_kind(w.group(1)) \
                and (re.match(r"[A-Z]\.", tgt) or re.match(r"[A-Z][a-z]+(?:[ ,]|['’]s)", tgt)):
            return "external", f"followed by {tgt[:30].strip()!r}", "rule"
    # "..., *Title*, Lemma 2.1", "arXiv:2512.11152, Lemma A.12", "De Silva (2011), Theorem 1.1"
    if re.search(r"(?:\*[^*\n]{3,}\*|arXiv:\s*\d{4}\.\d{4,5}(?:v\d+)?|\(\d{4}[a-z]?\)|et al\.)\s*,\s*$", before):
        if any(a in before for a in aliases):
            return "confirmed", "after a full reference to this paper", "rule"
        return "external", "after a reference to another work", "rule"
    m = re.search(r"(?:^|[(\[;:]|\bsee\s|\bcf\.\s)\s*([A-Z][\w'’\-–]+(?:\s+(?:et al\.|and|&)\s*[A-Z][\w'’\-–]+)*)"
                  r"(?:,|['’]s)\s*$", before)
    if m and m.group(1) not in _STOP_NAMES and not word_kind(m.group(1)):
        if any(a in m.group(1) for a in aliases):
            return "confirmed", f"after {m.group(1)!r}", "rule"
        return "external", f"after {m.group(1)!r}", "rule"
    for a in aliases:
        if a in sentence:
            return "confirmed", f"{a!r} nearby", "rule"
    for x in external:
        if x in sentence:
            return "external", f"{x!r} earlier in the sentence", "rule"
    return "plain", "", "rule"


def _index(snap: dict):
    by_num: dict[str, list[str]] = {}
    items: dict[tuple[str, str], str] = {}
    for name, e in snap["labels"].items():
        if e.get("kind") == "item":
            if e.get("parent"):
                items.setdefault((e["parent"], item_core(e["number"])), name)
            continue
        by_num.setdefault(e["number"], []).append(name)
    return by_num, items


def _resolve_target(target: str, item: str | None, labels: dict, items: dict, note: str) -> dict:
    if labels[target].get("kind") is None:
        note = (note + "; " if note else "") + "label kind unknown"
    if item:
        il = items.get((target, item_core(item)))
        if il:
            return {"status": "resolved", "label": il, "note": (note + "; " if note else "") + "enumerate item"}
        note = (note + "; " if note else "") + f"item {item.strip()} has no label (kept in link text)"
    return {"status": "resolved", "label": target, "note": note}


def _resolve(kind: str | None, num: str, item: str | None, snap: dict, idx) -> dict:
    by_num, items = idx
    cands = sorted(by_num.get(num, []))
    labels = snap["labels"]
    compat = [c for c in cands if kind_compatible(kind, labels[c].get("kind"))]
    if kind is not None and kind != "equation":
        compat = [c for c in compat if labels[c].get("kind") != "equation"]
    if kind is None:
        compat = [c for c in compat if labels[c].get("kind") not in STRUCTURAL_KINDS]
    if len(compat) == 1:
        return _resolve_target(compat[0], item, labels, items, "")
    if len(compat) > 1:
        anchors = {labels[c].get("anchor") for c in compat}
        primaries = {labels[c].get("alias_of") or c for c in compat}
        if len(primaries) == 1:
            prim = primaries.pop()
            others = ", ".join(c for c in compat if c != prim)
            res = _resolve_target(prim, item, labels, items, f"alias group; also labelled {others}")
            return res
        note = ("aliases of one target (same anchor); pick by meaning"
                if len(anchors) == 1 and None not in anchors else "several labels")
        return {"status": "ambiguous", "label": None, "candidates": compat, "note": note}
    others = [c for c in cands if labels[c].get("kind") not in STRUCTURAL_KINDS]
    if others and kind is not None and kind not in STRUCTURAL_KINDS:
        desc = ", ".join(f"{kind_display(labels[c]['kind'] or '?')} {num} = {c}" for c in others)
        return {"status": "mismatch", "label": None, "candidates": others, "note": f"now {desc}"}
    return {"status": "unresolvable", "label": None, "note": "no such number in this version"}


VERSION_TOKEN_RE = re.compile(r"(?<![\w`.-])v(\d+)(?![\w]|\.\d)")  # "v2", not "v0.1.0" or "...14981v2"


def display_text(seg: str) -> tuple[str, list[int]]:
    """``seg`` with link markup removed (``[text](#K:l)`` -> ``text``), plus a map from positions in
    ``seg`` to positions in the result. Context windows are taken on this text, so links inserted by
    an earlier bootstrap pass do not change what a later pass sees."""
    out, pos, last, k = [], [0] * (len(seg) + 1), 0, 0
    for m in REF_RE.finditer(seg):
        for i in range(last, m.start()):
            pos[i] = k; out.append(seg[i]); k += 1
        for i in range(m.start(), m.end()):
            pos[i] = k
            if m.start("text") <= i < m.end("text"):
                out.append(seg[i]); k += 1
        last = m.end()
    for i in range(last, len(seg)):
        pos[i] = k; out.append(seg[i]); k += 1
    pos[len(seg)] = k
    return "".join(out), pos


SENTENCE_END_RE = re.compile(r"\.\s|;|\n[ \t]*\n|\n[ \t]*(?:[-*+]|\d+[.)])\s")


def _sentence_parts(seg: str, start: int, end: int, width: int = 160) -> tuple[str, str]:
    """The parts of the sentence around seg[start:end]: (text before, text after). A sentence ends at
    '. ', ';', a blank line or the start of a list item."""
    before = seg[max(0, start - width):start]
    ends = [m.end() for m in SENTENCE_END_RE.finditer(before)]
    after = seg[end:end + width]
    m = SENTENCE_END_RE.search(after)
    return (before[ends[-1]:] if ends else before), (after[:m.start()] if m else after)


def _sentence(seg: str, start: int, end: int) -> str:
    b, a = _sentence_parts(seg, start, end)
    return b + " " + seg[start:end] + " " + a


def line_anchor(line_text: str) -> str:
    """Fingerprint of a source line: a reviewed decision applies only while its line is unchanged."""
    return hashlib.sha256(" ".join(line_text.split()).encode()).hexdigest()[:10]


def load_reviewed(cfg: Config, key: str) -> dict[tuple[str, int, str], tuple[str, str]]:
    """paper-refs/bootstrap-<KEY>-reviewed.tsv: per-citation decisions copied from a manifest
    (columns file, line, anchor, text, version; version is vN or "skip"). A row applies only while
    the line still has the manifest's anchor, so a decision never lands on another occurrence
    after the file was rewritten; a stale row is ignored and reported."""
    path = os.path.join(cfg.root, f"paper-refs/bootstrap-{key}-reviewed.tsv")
    out: dict[tuple[str, int, str], tuple[str, str]] = {}
    if not os.path.exists(path):
        return out
    rows = read_text(path).splitlines()
    head = rows[0].split("\t") if rows else []
    try:
        fi, li, ai, ti, vi = (head.index(c) for c in ("file", "line", "anchor", "text", "version"))
    except ValueError:
        die(f"{os.path.relpath(path, cfg.root)}: header must name the columns file, line, anchor, text, version")
    for r in rows[1:]:
        c = r.split("\t")
        if len(c) > max(fi, li, ai, ti, vi) and c[vi].strip():
            out[(c[fi], int(c[li]), " ".join(c[ti].split()))] = (c[vi].strip(), c[ai].strip())
    return out


def cited_version_of(cfg: Config, key: str, rel: str, sentence: str, run_version: str,
                     review: str | None) -> tuple[str, str, bool]:
    """(version a plain citation follows, why, explicit). Explicit: a reviewed decision, or a
    version named in its sentence ("the v2 Definition 2.3", "arXiv:2609.14981v2"). Otherwise
    bootstrap.cited_files, bootstrap.cited_default or the run's version, which are assumptions."""
    if review:
        return review, "reviewed", True
    toks = {f"v{m.group(1)}" for m in VERSION_TOKEN_RE.finditer(sentence)}
    arxiv = cfg.papers[key].get("arxiv")
    if arxiv:
        toks |= {m.group(1) for m in re.finditer(rf"(?<![\d.]){re.escape(str(arxiv))}(v\d+)(?![\w])", sentence)}
    if len(toks) == 1:
        t = toks.pop()
        return t, f"sentence names {t}", True
    if len(toks) > 1:
        return "?", f"sentence names {', '.join(sorted(toks))}", True
    vers = sorted({ver for g, ver in cfg.boot_cited_files if g.match(rel)})
    if len(vers) > 1:
        die(f"{CONFIG_REL}: bootstrap.cited_files assigns {rel} to several versions ({', '.join(vers)})")
    if vers:
        return vers[0], "bootstrap.cited_files", False
    if cfg.boot_cited_default:
        return str(cfg.boot_cited_default), "bootstrap.cited_default", False
    return run_version, "this pass", False


def bootstrap_scan(cfg: Config, snaps: dict[str, dict], only: str | None, edit: bool = False,
                   cited: str | None = None, versions: dict[str, dict[str, dict]] | None = None):
    """Find plain citations and resolve each in the version it follows.

    ``versions`` maps each paper to {version: snapshot} (main + references). A citation is
    resolved against the snapshot of its own version (other-version if there is none). An
    unmarked citation (its version is only assumed, see cited_version_of) whose number names a
    different label in another available version, or only resolves there, is needs-review: it
    is not written until a reviewed decision exists."""
    keys = [only] if only else [k for k in cfg.papers if k in snaps]
    if not keys:
        return []
    versions = versions or {k: {str(snaps[k]["version"]): snaps[k]} for k in keys}
    indices = {k: {v: _index(sn) for v, sn in versions[k].items()} for k in keys}
    reviewed = {k: load_reviewed(cfg, k) for k in keys}
    stale_reviews: list = []
    found = []
    for rel in iter_files(cfg, cfg.boot_exclude):
        path = os.path.join(cfg.root, rel)
        text = read_text(path)
        for a, b, _ in file_regions(rel, text):
            seg = text[a:b]
            masked = _mask(seg)
            dseg, dpos = display_text(seg)
            taken: list[tuple[int, int]] = []
            hits = []
            for m in PLAIN_RE.finditer(masked):
                kw = m.group("kw")
                k = word_kind(kw)
                if k is None:
                    continue
                if k == "equation" and not m.group("open") and "." not in m.group("num"):
                    continue  # "Differential Equations 65": a journal volume, not a citation
                if m.group("open") and k != "equation":
                    # "problem (3.4)", "condition (A.12)": an equation number after a prose word
                    elems = [(m.start("open"), m.end(), m.group("num"), m.group("item"), True, "equation")]
                else:
                    elems = [(m.start(), m.end(), m.group("num"), m.group("item"), True, k)]
                pos = m.end()
                while True:
                    t = LIST_TAIL_RE.match(masked, pos)
                    if not t:
                        break
                    ek = "equation" if t.group("open") else k
                    elems.append((t.start("open") if t.group("open") else t.start("num"), t.end(), t.group("num"),
                                  t.group("item"), False, ek))
                    pos = t.end()
                if len(elems) > 1 and all(el[5] == k for el in elems):
                    # a list: "Lemmas [2.3](..) and [2.4](..)"; the kind word stays outside the links
                    st = m.start("open") if m.group("open") else m.start("num")
                    elems[0] = (st,) + elems[0][1:]
                hits.append((kw, k, elems, m.start(), pos))
                taken.append((m.start(), pos))
            if cfg.boot_bare_equations:
                for m in BARE_EQ_RE.finditer(masked):
                    if any(s <= m.start() < e for s, e in taken):
                        continue
                    hits.append(("", "equation", [(m.start(), m.end(), m.group("num"), None, True, "equation")],
                                 m.start(), m.end()))
            for kw, k, elems, hs, he in sorted(hits, key=lambda h: h[3]):
                sentence = _sentence(dseg, dpos[hs], dpos[he])
                for (s, e, num, item, first, ek) in elems:
                    disp = seg[s:e]
                    ln = line_of(text, a + s)
                    rkey = (rel, ln, " ".join(disp.split()))
                    line_text = text[text.rfind("\n", 0, a + s) + 1:text.find("\n", a + s) % (len(text) + 1)]
                    anchor = line_anchor(line_text)
                    res_by_key, ctx_by_key, ver_by_key, nr_by_key = {}, {}, {}, {}
                    for key in keys:
                        ctx_by_key[key] = _context(dseg, dpos[hs], dpos[he], cfg.papers[key], cfg.boot_external)
                        run_ver = cited or str(cfg.papers[key]["version"])
                        rv = reviewed[key].get(rkey)
                        if rv and rv[1] != anchor:
                            stale_reviews.append((key, rel, ln, disp))
                            rv = None
                        ver, why, explicit = cited_version_of(cfg, key, rel, sentence, run_ver,
                                                              rv[0] if rv else None)
                        ver_by_key[key] = (ver, why, explicit)
                        if ver == "skip":
                            res_by_key[key] = {"status": "reviewed-skip", "label": None, "note": "reviewed: skip"}
                            continue
                        sn = versions[key].get(ver)
                        if sn is None:
                            res_by_key[key] = {"status": "other-version", "label": None,
                                               "note": f"follows {ver} ({why}); no snapshot for {ver}"}
                            continue
                        res = _resolve(ek, num, item, sn, indices[key][ver])
                        res_by_key[key] = res
                        if explicit:
                            continue
                        alt = []
                        for v2, sn2 in sorted(versions[key].items()):
                            if v2 == ver:
                                continue
                            r2 = _resolve(ek, num, item, sn2, indices[key][v2])
                            if r2["status"] != "resolved":
                                continue
                            if res["status"] != "resolved":
                                alt.append(f"only {v2} resolves: {r2['label']}")
                            elif r2["label"] != res["label"]:
                                alt.append(f"{ver}: {res['label']}; {v2}: {r2['label']}")
                        if alt:
                            nr_by_key[key] = "; ".join(alt)
                    confirmed = [key for key in keys if ctx_by_key[key][0] == "confirmed"]
                    pool = confirmed or keys
                    ext = all(ctx_by_key[key][0] == "external" for key in pool)
                    ok = [key for key in pool if res_by_key[key]["status"] == "resolved"]
                    conflict = [key for key in pool if ctx_by_key[key][0] == "conflict"]
                    exempt = None
                    if OTHER_WORK_MARK in line_text:
                        exempt = "other-work"
                    elif EXEMPT_MARK in line_text:
                        exempt = "plain"
                    else:
                        for g, t, ow in cfg.boot_exempt:
                            if g.match(rel) and " ".join(disp.split()) == " ".join(t.split()):
                                exempt = "other-work" if ow else "plain"
                    if exempt:
                        key = pool[0]
                        res = {"status": "exempt", "label": None, "note": f"exempted ({exempt})", "exempt": exempt}
                    elif all(res_by_key[kk]["status"] in ("other-version", "reviewed-skip") for kk in pool):
                        key = pool[0]
                        res = dict(res_by_key[key])
                    elif conflict:
                        key = conflict[0]
                        res = {"status": "ambiguous", "label": None,
                               "note": "conflicting context: " + ctx_by_key[key][1]}
                    elif ext:
                        key = pool[0]
                        res = {"status": "external", "label": None, "note": ctx_by_key[key][1]}
                    elif len(ok) == 1:
                        key = ok[0]
                        res = dict(res_by_key[key])
                    elif len(ok) > 1:
                        key = ok[0]
                        res = {"status": "ambiguous", "label": None, "note": "resolves in several papers: "
                               + ", ".join(ok)}
                    else:
                        key = pool[0]
                        res = dict(res_by_key[key])
                    if ek == "equation" and (not kw or k != "equation") and res["status"] == "unresolvable":
                        res["status"] = "eq-unresolvable"
                    if key in nr_by_key and res["status"] in ("resolved", "mismatch", "unresolvable", "eq-unresolvable"):
                        res = {"status": "needs-review", "label": None,
                               "candidates": [], "note": nr_by_key[key]}
                    if res["status"] == "resolved" and ctx_by_key[key][0] == "confirmed":
                        res["note"] = (res.get("note") + "; " if res.get("note") else "") + "confirmed by context"
                    ver, why, explicit = ver_by_key[key]
                    found.append({
                        "file": rel, "line": ln, "paper": key, "kind": ek,
                        "kind_word": kw, "number": num, "item": (item or "").strip(), "text": disp,
                        "status": res["status"], "label": res.get("label"),
                        "candidates": res.get("candidates", []), "note": res.get("note", ""),
                        "context": ctx_by_key[key][1], "version": ver,
                        "version_from": why + ("" if explicit else " (assumed)"),
                        "exempt": res.get("exempt"), "anchor": anchor, "_abs": (a + s, a + e), "_first": first,
                    })
    for key, rel, ln, disp in stale_reviews:
        print(f"{rel}:{ln}: warning: [stale-review] the reviewed decision for {disp!r} no longer matches the "
              "line (the file changed); review it again from a fresh `suggest --manifest`", file=sys.stderr)
    return found


def _tsv(v) -> str:
    return " ".join(str(v if v is not None else "").split())


MANIFEST_HEAD = "file\tline\tanchor\tstatus\tversion\twritten\tlabel\ttext\thow"


def write_manifest(cfg: Config, key: str, version: str, found: list, written: set, fresh: bool = False) -> str:
    rows = [MANIFEST_HEAD]
    for c in sorted((c for c in found if c["paper"] == key), key=lambda c: (c["file"], c["line"], c["_abs"])):
        how = "; ".join(x for x in (c["note"], c["context"]) if x)
        if c.get("candidates"):
            how = (how + "; " if how else "") + "candidates: " + ", ".join(c["candidates"])
        how = (how + "; " if how else "") + f"version from {c['version_from']}"
        rows.append("\t".join(_tsv(v) for v in (c["file"], c["line"], c["anchor"], c["status"], c["version"],
                                                 "yes" if (c["file"], c["_abs"]) in written else "no",
                                                 c["label"], c["text"], how)))
    rel = f"paper-refs/bootstrap-{key}-{version}.tsv"
    path = os.path.join(cfg.root, rel)
    old = read_text(path).splitlines() if os.path.exists(path) else []
    if not fresh and any(r.split("\t")[5:6] == ["yes"] for r in old[1:]):
        # a later --write pass adds its conversions to the record of the first
        new_conv = [r for r in rows[1:] if r.split("\t")[5] == "yes"]
        seen = set(old)
        rows = old + [r for r in new_conv if r not in seen]
    text = "\n".join(rows) + "\n"
    if not os.path.exists(path) or read_text(path) != text:
        write_text(path, text)
    return rel


def cmd_suggest(cfg: Config, args, write: bool = False) -> int:
    probs: list[Problem] = []
    if write:
        snaps, probs = preflight(cfg)
    else:
        snaps = load_all_snapshots(cfg, probs)
    versions = load_references(cfg, probs)
    keys = [args.paper] if args.paper else list(cfg.papers)
    if write:
        if len(keys) != 1:
            probs.append(Problem(CONFIG_REL, 0, "error", "bootstrap", "--write with several papers needs --paper"))
        elif keys[0] not in cfg.papers:
            die(f"unknown paper key {keys[0]!r}")
        else:
            key = keys[0]
            have = versions.get(key, {})
            if not args.cited:
                probs.append(Problem(CONFIG_REL, 0, "error", "bootstrap",
                                     "--write needs --cited <version>: the paper version the unmarked plain "
                                     f"citations were written against (snapshots: {', '.join(sorted(have))})"))
            elif args.cited not in have:
                probs.append(Problem(CONFIG_REL, 0, "error", "wrong-version",
                                     f"the code cites {args.cited!r} but there is no {key} snapshot for it "
                                     f"(have {', '.join(sorted(have)) or 'none'}): bootstrap only against the "
                                     "cited version (add a reference snapshot)"))
            for ver, sn in sorted(have.items()):
                if sn.get("draft") or (ver == str(cfg.papers[key]["version"]) and cfg.papers[key].get("draft")):
                    probs.append(Problem(CONFIG_REL, 0, "error", "bootstrap",
                                         f"{key} snapshot {ver} is a draft; bootstrap only against frozen versions"))
        if any(p.level == "error" for p in probs):
            emit(probs)
            print(f"{TOOL}: bootstrap stopped before writing anything")
            return 1
        only = keys[0]
    else:
        only = args.paper
        emit([p for p in probs if p.level == "error"])
    if only and only not in snaps:
        die(f"no snapshot for paper {only!r}")
    found = bootstrap_scan(cfg, snaps, only, cited=args.cited, versions=versions)
    counts: dict[str, int] = {}
    for c in found:
        counts[c["status"]] = counts.get(c["status"], 0) + 1
    if args.json:
        print(json.dumps({"counts": dict(sorted(counts.items())),
                          "items": [{k: v for k, v in c.items() if not k.startswith("_")} for c in found]},
                         indent=1, ensure_ascii=False, sort_keys=True))
    else:
        for c in found:
            if c["status"] == "resolved" and not args.verbose:
                continue
            tgt = f" -> {c['paper']}:{c['label']}" if c["label"] else ""
            cand = f" candidates: {', '.join(c['candidates'])}" if c.get("candidates") else ""
            note = f" ({c['note']})" if c["note"] else ""
            print(f"{c['file']}:{c['line']}: {c['status']}: {c['text']!r}{tgt}{cand}{note}")
        print(f"{TOOL}: " + ", ".join(f"{k} {v}" for k, v in sorted(counts.items())))
    if not write and getattr(args, "manifest", False):
        for key in ([only] if only else sorted(cfg.papers)):
            man = write_manifest(cfg, key, args.cited or str(cfg.papers[key]["version"]), found, set(), fresh=True)
            print(f"{TOOL}: wrote {man}")
    if write:
        by_file: dict[str, list] = {}
        for c in found:
            if c["status"] == "resolved":
                by_file.setdefault(c["file"], []).append(c)
        wprobs: list[Problem] = []
        written: set = set()
        for rel, cs in sorted(by_file.items()):
            path = os.path.join(cfg.root, rel)
            text = read_text(path)
            edits = []
            for c in cs:
                s0, e0 = c["_abs"]
                edits.append((s0, e0, f"[{text[s0:e0]}](#{c['paper']}:{c['label']})"))
            edits = drop_unwrappable(rel, text, edits, cfg.max_line, wprobs)
            kept = {(ed[0], ed[1]) for ed in edits}
            written |= {(c["file"], c["_abs"]) for c in cs if tuple(c["_abs"]) in kept}
            new = rewrap(rel, text, apply_edits(text, edits), cfg.max_line, wprobs)
            if new != text:
                write_text(path, new)
                print(f"converted {len(edits)} citation(s) in {rel}{module_note(rel)}")
        if written:  # a rerun that converts nothing keeps the manifest of the real migration
            man = write_manifest(cfg, only, args.cited, found, written)
            print(f"{TOOL}: review {man} ({len(written)} converted)")
        else:
            print(f"{TOOL}: nothing converted; manifest left unchanged")
        nr = counts.get("needs-review", 0)
        if nr:
            print(f"{TOOL}: {nr} citation(s) need review: copy their manifest rows into "
                  f"paper-refs/bootstrap-{only}-reviewed.tsv with a version (vN or skip)")
        emit(wprobs)
        return 1 if any(p.level == "error" for p in wprobs) else 0
    return 0


