LIST_SEP_RE = re.compile(r"\A\s*,?\s*(?:(?:and|or|to|&)\s+)?(?:–|—|--|-)?\s*\Z")
KW_BEFORE_RE = re.compile(rf"{KIND_WORD}[ \t\n~\xa0]*\Z")


def list_kind_words(text: str, refs: list[Ref]) -> dict[int, tuple[str, list[Ref]]]:
    """Number-only links that follow a kind word, e.g. ``Lemmas [2.3](..) and [2.4](..)``:
    {index of the first ref: (kind word, refs of the list)}."""
    out = {}
    i = 0
    while i < len(refs):
        if link_form(refs[i].text) not in ("num", "item"):
            i += 1
            continue
        j = i
        while j + 1 < len(refs) and link_form(refs[j + 1].text) in ("num", "item") \
                and LIST_SEP_RE.match(text[refs[j].end:refs[j + 1].start]):
            j += 1
        m = KW_BEFORE_RE.search(text[max(0, refs[i].start - 40):refs[i].start])
        if m:
            out[i] = (m.group("kw"), refs[i:j + 1])
        i = j + 1
    return out


def scan_refs(cfg: Config, snaps: dict[str, dict], fix: bool, dry_run: bool = False
              ) -> tuple[list[Problem], dict, dict[str, str]]:
    """Check (fix=False) or rewrite (fix=True) every link citation. Returns (problems, stats,
    {file: new text}); files are written only if fix and not dry_run."""
    probs: list[Problem] = []
    stats = {"files": 0, "refs": 0, "changed_refs": 0, "changed_files": 0, "free": 0}
    outputs: dict[str, str] = {}
    for rel in iter_files(cfg):
        path = os.path.join(cfg.root, rel)
        text = read_text(path)
        regions = file_regions(rel, text)
        edits = []
        refs = find_refs(text, regions)
        if refs:
            stats["files"] += 1
        for r in refs:
            stats["refs"] += 1
            ln = line_of(text, r.start)
            if r.key not in cfg.papers:
                probs.append(Problem(rel, ln, "error", "unknown-key",
                                     f"link target #{r.key}:{r.label}: {r.key!r} is not a configured paper"))
                continue
            snap = snaps.get(r.key)
            if snap is None:
                continue
            label = r.label
            rt, acc, _ = decisions_for(cfg, r.key, snap)
            if label in rt and rt[label] in snap["labels"]:
                label = rt[label]
            exp = expected_for(label, snap)
            if exp is None:
                hint = similar_labels(r.label, snap)
                gone = snap.get("removed", {}).get(r.label)
                probs.append(Problem(rel, ln, "error", "unknown-label",
                                     f"{r.key}:{r.label} is not a label of {r.key} {snap['version']} "
                                     f"(shown as {r.text!r})" + (f"; was {gone}" if gone else "")
                                     + (f"; renamed to {', '.join(hint)}? (decisions retarget)" if hint else "")))
                continue
            if label == r.label and label in snap.get("moved", {}) and label not in acc:
                probs.append(Problem(rel, ln, "error", "moved-label",
                                     f"{r.key}:{label} may name another statement since "
                                     f"{snap.get('moved_since')} ({snap['moved'][label]}); record a decision in "
                                     f"[papers.{r.key}.decisions.\"{decision_scope(snap)}\"]"))
                continue
            new, changes, flags = fix_link_text(r.text, exp)
            for fl in flags:
                probs.append(Problem(rel, ln, "error", "missing-item" if "item" in fl else "link-text",
                                     f"{r.key}:{label}: {fl}"))
            if link_form(r.text) == "free":
                stats["free"] += 1
                if LINK_KW_NUM_RE.search(r.text):
                    probs.append(Problem(rel, ln, "warning", "free-text",
                                         f"link text {r.text!r} is not a single leading citation, so its "
                                         "numbers are not maintained"))
            if label != r.label:
                changes.append(f"label {r.label} -> {label}")
            if changes:
                stats["changed_refs"] += 1
                if fix:
                    edits.append((r.start, r.end, f"[{new}](#{r.key}:{label})"))
                else:
                    probs.append(Problem(rel, ln, "error", "stale",
                                         f"{r.key}:{r.label} shows {r.text!r}, {r.key} {snap['version']} has "
                                         f"{new!r} ({'; '.join(changes)})"))
        # kind word in front of a number-only list: checked against every target, never rewritten
        for a, b, _ in regions:
            rr = [r for r in refs if a <= r.start < b]
            for _, (kw, members) in sorted(list_kind_words(text, rr).items()):
                wk = word_kind(kw)
                for r in members:
                    snap = snaps.get(r.key)
                    if not snap or r.key not in cfg.papers:
                        continue
                    if r.text.strip().startswith("(") and wk != "equation":
                        continue  # "problem [(3.4)](..)": a parenthesised number is an equation citation
                    lbl = decisions_for(cfg, r.key, snap)[0].get(r.label, r.label)
                    exp = expected_for(lbl, snap)
                    if exp and exp["kind"] and wk and not kind_compatible(wk, exp["kind"]):
                        probs.append(Problem(rel, line_of(text, r.start), "error", "stale-kind-word",
                                             f"{kw!r} before [{r.text}](#{r.key}:{r.label}) but it is "
                                             f"{kind_display(exp['kind'])} {exp['num']}; fix the wording by hand"))
        if fix and edits:
            new_text = rewrap(rel, text, apply_edits(text, edits), cfg.max_line, probs)
            if new_text != text:
                outputs[rel] = new_text
                stats["changed_files"] += 1
                if not dry_run:
                    write_text(path, new_text)
                    print(f"updated {rel} ({len(edits)} reference(s)){module_note(rel)}")
    return probs, stats, outputs


def similar_labels(label: str, snap: dict) -> list[str]:
    """Labels of the snapshot with the same name after the prefix (``eqn:foo`` ~ ``r.foo``)."""
    stem = re.split(r"[.:]", label, maxsplit=1)[-1].lower()
    return sorted(n for n in snap["labels"] if re.split(r"[.:]", n, maxsplit=1)[-1].lower() == stem)[:3]


def check_version_mentions(cfg: Config, probs: list[Problem]) -> None:
    """Warn where README/metadata name another arXiv version of a configured paper."""
    for rel in ("README.md", "CITATION.cff", "formalization.yaml"):
        path = os.path.join(cfg.root, rel)
        if not os.path.exists(path):
            continue
        text = read_text(path)
        for key, p in cfg.papers.items():
            aid = p.get("arxiv")
            if not aid:
                continue
            for m in re.finditer(rf"{re.escape(aid)}(v\d+)", text):
                if m.group(1) != str(p["version"]):
                    probs.append(Problem(rel, line_of(text, m.start()), "warning", "version-mention",
                                         f"mentions {aid}{m.group(1)} but {key} citations follow {p['version']}"))


def module_note(rel: str) -> str:
    """' -> module A.B.C' for a .lean file (it and its importers will rebuild)."""
    if not rel.endswith(".lean"):
        return ""
    return " -> module " + rel[: -len(".lean")].replace("/", ".")


def cmd_sync(cfg: Config, args) -> int:
    snaps, probs = preflight(cfg)
    if any(p.level == "error" for p in probs):
        emit(probs)
        print(f"{TOOL}: sync stopped before writing anything (snapshot/config errors above)")
        return 1
    sp, stats, _ = scan_refs(cfg, snaps, fix=True)
    probs += sp
    emit(probs)
    print(f"{TOOL}: {stats['refs']} reference(s) in {stats['files']} file(s); "
          f"{stats['changed_refs']} updated in {stats['changed_files']} file(s)")
    return 1 if any(p.level == "error" for p in probs) else 0


def release_problems(cfg: Config, snaps: dict[str, dict]) -> list[Problem]:
    probs = []
    for key, p in cfg.papers.items():
        if p.get("draft"):
            probs.append(Problem(CONFIG_REL, 0, "error", "draft",
                                 f"papers.{key} is marked draft: released numbers must follow a frozen revision"))
        snap = snaps.get(key)
        if snap is not None and not release_ready(cfg, key, snap):
            fz = snap["source"].get("frozen") or {}
            why = ("its aux was not compiled from the commit (--aux-unverified)" if fz.get("unverified")
                   else eprint_problem(cfg, key, fz["eprint"], snap["version"]) if fz.get("eprint")
                   else "no frozen provenance")
            probs.append(Problem(os.path.relpath(cfg.snapshot_path(key), cfg.root), 0, "error", "not-frozen",
                                 f"{key} snapshot: {why}; rebuild it with `snapshot {key} --frozen <tag>` "
                                 "(or --eprint <id>v<N>)"))
    return probs


def cmd_check(cfg: Config, args) -> int:
    snaps, probs = preflight(cfg)
    sp, stats, _ = scan_refs(cfg, snaps, fix=False)
    probs += [p for p in sp if p.code != "moved-label"]  # reported once per label by preflight
    check_version_mentions(cfg, probs)
    if args.release:
        probs += release_problems(cfg, snaps)
        for p in probs:  # a release must not say one version and cite another
            if p.code == "version-mention":
                p.level = "error"
    for key in cfg.papers:  # optional local freshness check
        aux = cfg.paths(key, "aux")
        if key in snaps and aux and all(os.path.exists(a) for a in aux):
            _, digest = read_aux_tree(aux)
            if digest != snaps[key]["source"].get("aux_sha256"):
                probs.append(Problem(os.path.relpath(cfg.snapshot_path(key), cfg.root), 0, "warning",
                                     "snapshot-old", f"the local aux of {key} differs from the snapshot; "
                                     "run snapshot (and bump version if the numbering is new)"))
    if args.strict:
        found = bootstrap_scan(cfg, snaps, None, versions=load_references(cfg, probs))
        bad = {"resolved", "needs-review", "other-version"}
        if args.release:  # the release target: no plain citation of our paper is left
            bad |= {"mismatch", "ambiguous"}
        for c in found:
            st = c["status"]
            if st == "exempt" and args.release and c.get("exempt") != "other-work":
                probs.append(Problem(c["file"], c["line"], "error", "plain-citation",
                                     f"plain {c['text']!r} is exempted, but a release allows exemptions only "
                                     "for other works (`paper-refs: other-work`, exempt.other_work = true)"))
            elif st in bad:
                hint = (f"could be [{c['text']}](#{c['paper']}:{c['label']})" if st == "resolved"
                        else f"{st}: {c['note']}")
                probs.append(Problem(c["file"], c["line"], "error", "plain-citation",
                                     f"plain {c['text']!r} {hint}"))
    emit(probs)
    nerr = sum(p.level == "error" for p in probs)
    print(f"{TOOL}: {stats['refs']} reference(s) in {stats['files']} file(s); "
          f"{nerr} error(s), {sum(p.level == 'warning' for p in probs)} warning(s)")
    return 1 if nerr else 0


