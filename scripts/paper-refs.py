def load_tex(path: str, seen: set[str] | None = None) -> str:
    seen = seen if seen is not None else set()
    real = os.path.realpath(path)
    if real in seen or not os.path.exists(path):
        return ""
    seen.add(real)
    lines = []
    for line in read_text(path).splitlines():
        lines.append(re.sub(r"(?<!\\)%.*", "", line))
    text = "\n".join(lines)
    base = os.path.dirname(path)

    def repl(m):
        name = m.group(2).strip()
        cand = os.path.join(base, name)
        if not os.path.exists(cand) and os.path.exists(cand + ".tex"):
            cand += ".tex"
        return load_tex(cand, seen)

    return re.sub(r"\\(input|include|subfile)\{([^}]+)\}", repl, text)


def scan_tex(paths: list[str]) -> tuple[dict[str, dict], dict[str, str]]:
    """Return ({label: {"kind", "parent"}}, {env: display name}) from LaTeX sources."""
    text = "\n".join(load_tex(p) for p in paths)
    envs: dict[str, str] = {}
    for m in re.finditer(r"\\newtheorem\*?\{([^}]+)\}(?:\[[^\]]*\])?\{([^}]*)\}", text):
        envs[m.group(1).strip()] = clean_tex(m.group(2))
    for m in re.finditer(r"\\(?:declaretheorem|newtheorem)\[([^\]]*)\]\{([^}]+)\}", text):
        nm = re.search(r"name\s*=\s*\{?([^,}\]]+)", m.group(1))
        envs[m.group(2).strip()] = clean_tex(nm.group(1)) if nm else m.group(2).strip().capitalize()

    info: dict[str, dict] = {}
    stack: list[dict] = []
    section_kind = None
    in_appendix = False
    tok = re.compile(
        r"\\(?P<be>begin|end)\{(?P<env>[^}]+)\}|\\label\{(?P<label>[^}]+)\}"
        r"|\\(?P<sec>part|chapter|section|subsection|subsubsection|paragraph)\b\*?"
        r"|\\(?P<app>appendix)\b|\\(?P<item>item)\b"
    )
    top_sec = "chapter" if re.search(r"\\chapter\b", text) else "section"
    for m in tok.finditer(text):
        if m.group("be") == "begin":
            env = m.group("env").strip()
            frame = {"env": env, "label": None, "items": 0, "pending": []}
            if env in envs:
                frame["type"], frame["kind"] = "thm", canon_kind(envs[env])
            elif env.rstrip("*") in EQ_ENVS:
                frame["type"] = "eq"
            elif env in LIST_ENVS:
                frame["type"] = "list"
            elif env in FLOAT_ENVS:
                frame["type"], frame["kind"] = "float", FLOAT_ENVS[env]
            else:
                frame["type"] = "other"
            stack.append(frame)
        elif m.group("be") == "end":
            env = m.group("env").strip()
            for k in range(len(stack) - 1, -1, -1):
                if stack[k]["env"] == env:
                    fr = stack[k]
                    if fr["type"] == "thm":
                        for lbl in fr["pending"]:
                            info[lbl]["parent"] = fr["label"]
                    del stack[k:]
                    break
        elif m.group("sec"):
            level = m.group("sec")
            section_kind = "appendix" if (in_appendix and level == top_sec) else "section"
        elif m.group("app"):
            in_appendix = True
        elif m.group("item"):
            for fr in reversed(stack):
                if fr["type"] == "list":
                    fr["items"] += 1
                    break
        else:
            lbl = m.group("label").strip()
            entry = {"kind": None, "parent": None}
            relevant = [fr for fr in stack if fr["type"] != "other"]
            top = relevant[-1] if relevant else None
            if top is None:
                entry["kind"] = section_kind
            elif top["type"] == "eq":
                entry["kind"] = "equation"
            elif top["type"] == "float":
                entry["kind"] = top["kind"]
            elif top["type"] == "list" and top["items"] > 0:
                entry["kind"] = "item"
                thm = next((fr for fr in reversed(relevant) if fr["type"] == "thm"), None)
                if thm is not None:
                    if thm["label"] is not None:
                        entry["parent"] = thm["label"]
                    else:
                        thm["pending"].append(lbl)
            elif top["type"] == "thm":
                entry["kind"] = top["kind"]
                if top["label"] is None:
                    top["label"] = lbl
                else:
                    entry["alias_of"] = top["label"]
            else:  # list before the first \item
                thm = next((fr for fr in reversed(relevant) if fr["type"] == "thm"), None)
                if thm is not None:
                    entry["kind"] = thm["kind"]
                    thm["label"] = thm["label"] or lbl
            info[lbl] = entry
    return info, envs


