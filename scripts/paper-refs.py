def _desc(e: dict) -> str:
    return f"{kind_display(e['kind']) if e.get('kind') else '?'} {e['number']}"


def alias_groups(labels: dict) -> dict[str, list[str]]:
    groups: dict[str, list[str]] = {}
    for n, e in labels.items():
        if e.get("alias_of"):
            groups.setdefault(e["alias_of"], []).append(n)
    return {k: sorted(v) for k, v in groups.items()}


def diff_snapshots(rel: str, old: dict, new: dict) -> tuple[dict, dict, list[Problem]]:
    """Compare two revisions. Returns ({moved label: reason}, {removed label: description},
    warnings). A label is "moved" when it may now name a different statement: its kind,
    title, alias group or item parent changed. Renumbering alone is not a move."""
    ol, nl = old["labels"], new["labels"]
    probs = []
    moved: dict[str, str] = {}
    removed: dict[str, str] = {}
    renum = sorted(n for n in ol if n in nl and ol[n]["number"] != nl[n]["number"])
    added = sorted(set(nl) - set(ol))
    og, ng = alias_groups(ol), alias_groups(nl)
    for n in sorted(set(ol) - set(nl)):
        hint = similar_labels(n, new)
        removed[n] = f"{_desc(ol[n])} in {old.get('version')}"
        probs.append(Problem(rel, 0, "warning", "label-removed",
                             f"{n} ({_desc(ol[n])}) is gone" + (f"; renamed to {', '.join(hint)}?" if hint else "")))
    for n in sorted(set(ol) & set(nl)):
        a, b = ol[n], nl[n]
        why = []
        if a.get("kind") != b.get("kind"):  # including a kind that appears or disappears
            why.append(f"kind {_desc(a)} -> {_desc(b)}")
        if (a.get("title") or "") != (b.get("title") or ""):
            why.append(f"title {a.get('title') or '(none)'!r} -> {b.get('title') or '(none)'!r}")
        if a.get("alias_of") != b.get("alias_of"):
            why.append(f"alias of {a.get('alias_of') or '-'} -> {b.get('alias_of') or '-'}")
        if og.get(n, []) != ng.get(n, []):
            why.append(f"also labelled {', '.join(og.get(n, [])) or '-'} -> {', '.join(ng.get(n, [])) or '-'}")
        if a.get("kind") == "item" and a.get("parent") != b.get("parent"):
            why.append(f"item of {a.get('parent')} -> item of {b.get('parent')}")
        if why:
            moved[n] = f"{_desc(a)} -> {_desc(b)}: " + "; ".join(why)
            probs.append(Problem(rel, 0, "warning", "label-moved?", f"{n}: {moved[n]}"))
    print(f"{rel}: {old.get('version')} -> {new.get('version')}: {len(renum)} renumbered, "
          f"{len(removed)} removed, {len(added)} added, {len(moved)} possibly moved")
    return moved, removed, probs


def cited_labels(cfg: Config) -> dict[str, dict[str, list[str]]]:
    """{paper key: {label: ["file:line", ...]}} of every link citation in the repository."""
    out: dict[str, dict[str, list[str]]] = {}
    for rel in iter_files(cfg):
        text = read_text(os.path.join(cfg.root, rel))
        for r in find_refs(text, file_regions(rel, text)):
            out.setdefault(r.key, {}).setdefault(r.label, []).append(f"{rel}:{line_of(text, r.start)}")
    return out


def source_ident(snap: dict) -> str:
    """What a set of identity decisions was reviewed against: the frozen commit, the e-print,
    or (for anything else) a hash of both the aux and the .tex. A draft whose .tex changes while
    its aux stays the same (a moved title, say) is then a new source and needs a new review."""
    fz = snap["source"].get("frozen") or {}
    if fz.get("repo_commit") and not fz.get("unverified"):
        return fz["repo_commit"]
    if fz.get("eprint"):
        return fz["eprint"]
    return source_digest(snap["source"]["aux_sha256"], snap["source"].get("tex_sha256"))


def source_digest(aux_sha: str, tex_sha: str | None) -> str:
    return "src:" + hashlib.sha256(f"{aux_sha}\n{tex_sha or ''}".encode()).hexdigest()


def decision_scope(snap: dict) -> str | None:
    return f"{snap['moved_since']}->{snap['version']}" if snap.get("moved_since") else None


def decisions_for(cfg: Config, key: str, snap: dict) -> tuple[dict, set, list[Problem]]:
    """(retarget, accepted labels, problems) for the snapshot's own revision transition.

    Decisions live in ``[papers.KEY.decisions."<from>-><to>"]`` and apply only while the snapshot
    records that transition (``moved_since`` -> ``version``) and was built from the source named in
    ``reviewed``. A later move of the same label (a new revision, or a rebuilt draft) therefore
    needs a new decision. A retarget target counts as accepted: it was chosen in the new revision."""
    scope = decision_scope(snap)
    tables = cfg.papers[key].get("decisions") or {}
    if scope is None or scope not in tables:
        return {}, set(), []
    d = tables[scope]
    ident, rev = source_ident(snap), str(d["reviewed"])
    ok = ident == rev or (len(rev) >= 7 and ident.startswith(rev))
    if not ok:
        return {}, set(), [Problem(CONFIG_REL, 0, "error", "decisions-stale",
                                   f"papers.{key}.decisions.\"{scope}\" was reviewed against {rev!r}, but the "
                                   f"snapshot comes from {ident[:16]!r}: review the revision diff again and "
                                   "update 'reviewed'")]
    rt = {str(a): str(b) for a, b in (d.get("retarget") or {}).items()}
    acc = {str(a) for a in (d.get("accept_moved") or [])} | set(rt.values())
    return rt, acc, []


def identity_problems(cfg: Config, key: str, snap: dict, cites: dict[str, list[str]], rel: str) -> list[Problem]:
    """Errors for cited labels whose identity changed and has no recorded decision."""
    rt, acc, probs = decisions_for(cfg, key, snap)
    probs = list(probs)
    since = snap.get("moved_since", "?")
    for lbl, locs in sorted(cites.items()):
        if lbl in rt or lbl in acc:
            continue
        where = f"cited at {locs[0]}" + (f" (+{len(locs) - 1})" if len(locs) > 1 else "")
        if lbl in snap.get("moved", {}):
            probs.append(Problem(rel, 0, "error", "moved-label",
                                 f"{key}:{lbl} may name another statement since {since} "
                                 f"({snap['moved'][lbl]}); {where}. Record a decision in "
                                 f"[papers.{key}.decisions.\"{decision_scope(snap)}\"] "
                                 f"(retarget or accept_moved, reviewed = \"{source_ident(snap)[:12]}\")"))
        elif lbl in snap.get("removed", {}) and lbl not in snap["labels"]:
            hint = similar_labels(lbl, snap)
            probs.append(Problem(rel, 0, "error", "removed-label",
                                 f"{key}:{lbl} ({snap['removed'][lbl]}) is gone; {where}. Record a retarget in "
                                 f"[papers.{key}.decisions.\"{decision_scope(snap)}\"]"
                                 + (f" (renamed to {', '.join(hint)}?)" if hint else "")))
    return probs


def config_problems(cfg: Config, snaps: dict[str, dict]) -> list[Problem]:
    probs = []
    for key in cfg.papers:
        snap = snaps.get(key)
        if snap is None:
            continue
        scope = decision_scope(snap)
        d = (cfg.papers[key].get("decisions") or {}).get(scope) if scope else None
        if not d:
            continue
        for a, b in sorted((d.get("retarget") or {}).items()):
            if b not in snap["labels"]:
                probs.append(Problem(CONFIG_REL, 0, "error", "bad-retarget",
                                     f"decisions.\"{scope}\".retarget: {a} -> {b}, but {b} is not a label of "
                                     f"{key} {snap['version']}"))
            if a in set(d.get("accept_moved") or []):
                probs.append(Problem(CONFIG_REL, 0, "error", "bad-retarget",
                                     f"decisions.\"{scope}\": {a} is both retargeted and accepted"))
            # sync keeps an item suffix such as "(i)" in the link text, which is wrong once the
            # target is a whole result rather than an item of it
            if str(snap.get("removed", {}).get(a, "")).startswith("Item ") \
                    and snap["labels"].get(b, {}).get("kind") != "item":
                probs.append(Problem(CONFIG_REL, 0, "error", "bad-retarget",
                                     f"decisions.\"{scope}\".retarget: {a} is an item but {b} is not; sync "
                                     "would keep the old item suffix in the link text. Retarget each "
                                     "citation by hand (to an item label where possible)"))
        for a in sorted(set(d.get("accept_moved") or [])):
            if a not in snap["labels"]:
                probs.append(Problem(CONFIG_REL, 0, "error", "bad-accept",
                                     f"decisions.\"{scope}\".accept_moved: {a} is not a label of {key} {snap['version']}"))
    return probs


def git(repo: str, *argv: str) -> str | None:
    try:
        r = subprocess.run(["git", "-C", repo, *argv], capture_output=True, text=True, check=False)
    except OSError:
        return None
    return r.stdout.strip() if r.returncode == 0 else None


def frozen_build(cfg: Config, key: str, ref: str, aux: list[str], tex: list[str]
                 ) -> tuple[str | None, list[str], list[str], dict | None, list[str]]:
    """Export ``ref`` of the paper repository (git archive) into a fresh directory and compile it.
    Returns (build dir, aux paths, tex paths, provenance, errors). The aux is then provably
    produced from that commit."""
    probe = tex[0] if tex else aux[0]
    repo = git(os.path.dirname(os.path.abspath(probe)), "rev-parse", "--show-toplevel")
    if repo is None:
        return None, [], [], None, [f"--frozen: {probe} is not inside a git checkout of the paper"]
    commit = git(repo, "rev-parse", "--verify", "--quiet", f"{ref}^{{commit}}")
    if commit is None:
        return None, [], [], None, [f"--frozen: {ref!r} is not a commit or tag of {repo}"]
    real_repo = os.path.realpath(repo)
    mains = tex or [os.path.splitext(a)[0] + ".tex" for a in aux[:1]]
    rel_tex = [os.path.relpath(os.path.realpath(t), real_repo) for t in mains]
    rel_aux = [os.path.relpath(os.path.realpath(a), real_repo) for a in aux]
    if any(r.startswith("..") for r in rel_tex + rel_aux):
        return None, [], [], None, ["--frozen: the configured aux/tex must lie inside the paper repository"]
    build = tempfile.mkdtemp(prefix="paper-refs-frozen-")
    arch = subprocess.run(["git", "-C", repo, "archive", "--format=tar", commit], capture_output=True)
    if arch.returncode != 0:
        shutil.rmtree(build, ignore_errors=True)
        return None, [], [], None, [f"--frozen: git archive {ref} failed: {arch.stderr.decode()[-300:]}"]
    with tarfile.open(fileobj=io.BytesIO(arch.stdout)) as tf:
        try:
            tf.extractall(build, filter="data")
        except TypeError:  # Python < 3.12
            tf.extractall(build)
    cmd = [str(c) for c in (cfg.papers[key].get("latex") or DEFAULT_LATEX)]
    main = os.path.join(build, rel_tex[0])
    if not os.path.exists(main):
        shutil.rmtree(build, ignore_errors=True)
        return None, [], [], None, [f"--frozen: {rel_tex[0]} is not in {ref}"]
    if shutil.which(cmd[0]) is None:
        shutil.rmtree(build, ignore_errors=True)
        return None, [], [], None, [f"--frozen: {cmd[0]} not found (configure papers.{key}.latex)"]
    r = subprocess.run(cmd + [os.path.basename(main)], cwd=os.path.dirname(main), capture_output=True, text=True)
    built_aux = [os.path.join(build, a) for a in rel_aux]
    if r.returncode != 0 or not all(os.path.exists(a) for a in built_aux):
        tail = (r.stdout + r.stderr)[-400:]
        shutil.rmtree(build, ignore_errors=True)
        return None, [], [], None, [f"--frozen: compiling {rel_tex[0]} at {ref} failed: {tail}"]
    prov = {"repo_commit": commit, "compile": " ".join(cmd + [rel_tex[0]])}
    if git(repo, "rev-parse", "--verify", "--quiet", f"refs/tags/{ref}") is not None:
        prov["tag"] = ref
    return build, built_aux, [os.path.join(build, t) for t in rel_tex], prov, []


def frozen_provenance(ref: str, aux: list[str], tex: list[str]) -> tuple[dict | None, list[str]]:
    """--aux-unverified: check that the given aux sits in a clean checkout at ``ref``. This does not
    prove the aux was compiled from that commit, so check --release rejects it."""
    errs: list[str] = []
    repo = git(os.path.dirname(os.path.abspath(aux[0])), "rev-parse", "--show-toplevel")
    if repo is None:
        return None, [f"--frozen: {aux[0]} is not inside a git checkout of the paper"]
    want = git(repo, "rev-parse", "--verify", "--quiet", f"{ref}^{{commit}}")
    head = git(repo, "rev-parse", "HEAD")
    if want is None:
        errs.append(f"--frozen: {ref!r} is not a commit or tag of {repo}")
    elif head != want:
        errs.append(f"--frozen: {repo} is at {head[:12] if head else '?'}, not {ref} ({want[:12]}); check it out")
    dirty = git(repo, "status", "--porcelain", "--untracked-files=no")
    if dirty:
        errs.append(f"--frozen: {repo} has uncommitted changes to tracked files")
    for t in tex:
        if git(repo, "ls-files", "--error-unmatch", os.path.relpath(os.path.realpath(t), os.path.realpath(repo))) is None:
            errs.append(f"--frozen: {t} is not a tracked file of {repo}")
    newest_tex = max((os.path.getmtime(t) for t in tex if os.path.exists(t)), default=0)
    if newest_tex and min(os.path.getmtime(a) for a in aux) < newest_tex:
        errs.append("--frozen: the aux is older than the .tex; recompile the paper at this commit")
    if errs:
        return None, errs
    prov = {"repo_commit": want, "unverified": True}
    if git(repo, "rev-parse", "--verify", "--quiet", f"refs/tags/{ref}") is not None:
        prov["tag"] = ref
    return prov, []


EPRINT_RE = re.compile(r"\d{4}\.\d{4,5}v\d+|[a-z.-]+/\d{7}v\d+")


def eprint_problem(cfg: Config, key: str, eprint: str, version: str) -> str | None:
    """The e-print must name the configured paper and the snapshot's version."""
    if not EPRINT_RE.fullmatch(eprint):
        return f"e-print {eprint!r}: want <id>v<N>"
    want = f"{cfg.papers[key].get('arxiv', '')}{version}"
    if eprint != want:
        return f"e-print {eprint!r} does not match papers.{key} (arxiv {cfg.papers[key].get('arxiv')!r}, " \
               f"version {version!r}: want {want!r})"
    return None


def cmd_snapshot(cfg: Config, args) -> int:
    keys = args.keys or list(cfg.papers)
    for k in keys:
        if k not in cfg.papers:
            die(f"unknown paper key {k!r}")
    if (args.aux or args.tex or args.frozen or args.eprint or args.out) and len(keys) != 1:
        die("--aux/--tex/--frozen/--eprint/--out need exactly one paper key")
    if args.frozen and args.eprint:
        die("use --frozen or --eprint, not both")
    if args.aux_unverified and not args.frozen:
        die("--aux-unverified only modifies --frozen")
    if bool(args.out) != bool(args.as_version):
        die("--out and --as-version go together (a reference snapshot of another version)")
    cites = cited_labels(cfg)
    rc = 0
    for key in keys:
        aux = [os.path.abspath(a) for a in args.aux] if args.aux else cfg.paths(key, "aux")
        tex = [os.path.abspath(t) for t in args.tex] if args.tex else cfg.paths(key, "tex")
        if not aux:
            die(f"papers.{key}: no aux path (config 'aux' or --aux)")
        reference = bool(args.out)
        path = os.path.join(cfg.root, args.out) if reference else cfg.snapshot_path(key)
        rel = os.path.relpath(path, cfg.root)
        version = args.as_version or str(cfg.papers[key]["version"])
        probs: list[Problem] = []
        for t in tex:
            if not os.path.exists(t):
                probs.append(Problem(rel, 0, "error", "missing-tex", f"configured .tex not found: {t}"))
        if any(p.level == "error" for p in probs):
            emit(probs)
            rc = 1
            continue
        build, prov = None, None
        if args.frozen and not args.aux_unverified:
            build, aux, tex, prov, errs = frozen_build(cfg, key, args.frozen, aux, tex)
            if errs:
                emit([Problem(rel, 0, "error", "not-frozen", e) for e in errs])
                rc = 1
                continue
        try:
            draft = (not (args.frozen or args.eprint)) if reference else None
            snap, bprobs = build_snapshot(cfg, key, aux, tex, version=version, draft=draft)
        finally:
            if build:
                shutil.rmtree(build, ignore_errors=True)
        probs += bprobs
        if args.frozen and args.aux_unverified:
            prov, errs = frozen_provenance(args.frozen, aux, tex)
            probs += [Problem(rel, 0, "error", "not-frozen", e) for e in errs]
        if prov:
            snap["source"]["frozen"] = prov
        if args.eprint:
            err = eprint_problem(cfg, key, args.eprint, version)
            if err:
                probs.append(Problem(rel, 0, "error", "not-frozen", err))
            else:
                snap["source"]["frozen"] = {"eprint": args.eprint}
        if not snap["draft"] and not release_ready(cfg, key, snap):
            probs.append(Problem(rel, 0, "warning", "not-frozen",
                                 "draft = false but no verified --frozen/--eprint provenance: check --release will fail"))
        old = None if reference else load_snapshot(cfg, key)
        snap["moved"], snap["removed"], snap["moved_since"] = {}, {}, None
        if old:
            same_source = all(old["source"].get(h) == snap["source"].get(h) for h in ("aux_sha256", "tex_sha256"))
            if same_source and str(old.get("version")) == snap["version"]:
                moved, removed = {}, {}
            else:
                moved, removed, dprobs = diff_snapshots(rel, old, snap)
                probs += dprobs
            if str(old.get("version")) == snap["version"]:  # another build of the same revision
                moved = {**old.get("moved", {}), **moved}
                removed = {**old.get("removed", {}), **removed}
                since = old.get("moved_since") or (old["version"] if moved or removed else None)
            else:
                since = old["version"]
            snap["moved"] = {k: v for k, v in sorted(moved.items()) if k in snap["labels"]}
            snap["removed"] = {k: v for k, v in sorted(removed.items()) if k not in snap["labels"]}
            snap["moved_since"] = since if (snap["moved"] or snap["removed"]) else None
            if old["source"].get("aux_sha256") != snap["source"]["aux_sha256"] \
                    and str(old.get("version")) == snap["version"] and not snap["draft"]:
                probs.append(Problem(rel, 0, "warning", "version-unchanged",
                                     f"the aux changed but version is still {snap['version']!r}; "
                                     "bump 'version' (or set draft = true) if the numbering is new"))
        if snap["moved_since"] is None:
            for k in ("moved", "removed", "moved_since"):
                del snap[k]
        if not reference:
            # the identity gate: cited labels that changed meaning need a recorded decision
            probs += identity_problems(cfg, key, snap, cites.get(key, {}), rel)
            probs += config_problems(cfg, {key: snap})
        if snap["duplicates"]:
            probs += [Problem(rel, 0, "error", "duplicate-label", f"label {d!r} is multiply defined in the paper")
                      for d in snap["duplicates"]]
        emit(probs)
        if any(p.level == "error" for p in probs):
            print(f"{rel}: not written (fix the errors above)")
            rc = 1
            continue
        text = dump_snapshot(snap)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        if not os.path.exists(path) or read_text(path) != text:
            write_text(path, text)
            print(f"wrote {rel} ({len(snap['labels'])} labels{', reference ' + version if reference else ''})")
        else:
            print(f"{rel} up to date ({len(snap['labels'])} labels)")
    return rc


def release_ready(cfg: Config, key: str, snap: dict) -> bool:
    fz = snap["source"].get("frozen") or {}
    if fz.get("repo_commit") and fz.get("compile") and not fz.get("unverified"):
        return True
    return bool(fz.get("eprint")) and eprint_problem(cfg, key, fz["eprint"], snap["version"]) is None


