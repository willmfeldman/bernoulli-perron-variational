def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog=f"{TOOL}.py", description=__doc__.split("\n\n")[0])
    ap.add_argument("--root", default=".", help="repository root (default: current directory)")
    ap.add_argument("--version", action="version", version=f"{TOOL} {TOOL_VERSION}")
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("snapshot", help="write paper-refs/<KEY>.json from LaTeX .aux (+ .tex)")
    p.add_argument("keys", nargs="*")
    p.add_argument("--aux", action="append", default=[])
    p.add_argument("--tex", action="append", default=[])
    p.add_argument("--frozen", metavar="REF", help="export this tag or commit of the paper repository, compile it "
                   "and snapshot the result (required for check --release)")
    p.add_argument("--eprint", metavar="ID", help="record that the aux was built from this arXiv e-print "
                   "(<id>v<N>; must match the config) instead")
    p.add_argument("--aux-unverified", action="store_true", help="with --frozen: use the configured aux of a clean "
                   "checkout at REF instead of compiling an export (check --release rejects this)")
    p.add_argument("--out", metavar="PATH", help="write a reference snapshot of another version to PATH "
                   "(with --as-version; no identity gate)")
    p.add_argument("--as-version", metavar="VERSION", help="the version of a reference snapshot")
    sub.add_parser("sync", help="rewrite displayed numbers from the snapshots")
    p = sub.add_parser("check", help="fail on unknown labels, stale numbers, duplicates")
    p.add_argument("--release", action="store_true", help="also require draft = false and a frozen snapshot")
    p.add_argument("--strict", action="store_true", help="also fail on convertible plain citations")
    for name in ("suggest", "bootstrap"):
        p = sub.add_parser(name, help="find plain-text citations" + (" and convert them" if name == "bootstrap" else ""))
        p.add_argument("--paper")
        p.add_argument("--json", action="store_true")
        p.add_argument("--verbose", "-v", action="store_true", help="also list resolved citations")
        p.add_argument("--cited", metavar="VERSION", help="the paper version this pass handles; with --write it "
                       "must equal the config and snapshot version")
        if name == "bootstrap":
            p.add_argument("--write", action="store_true", help="convert the uniquely resolved citations")
        else:
            p.add_argument("--manifest", action="store_true", help="write paper-refs/bootstrap-<KEY>-<version>.tsv "
                           "without converting anything (for review)")
    p = sub.add_parser("report", help="coverage table of cited labels")
    p.add_argument("--all", action="store_true", help="include equations, sections and items")
    p.add_argument("--json", action="store_true")
    args = ap.parse_args(argv)
    cfg = load_config(os.path.abspath(args.root))
    if args.cmd == "snapshot":
        return cmd_snapshot(cfg, args)
    if args.cmd == "sync":
        return cmd_sync(cfg, args)
    if args.cmd == "check":
        return cmd_check(cfg, args)
    if args.cmd == "suggest":
        return cmd_suggest(cfg, args)
    if args.cmd == "bootstrap":
        return cmd_suggest(cfg, args, write=args.write)
    if args.cmd == "report":
        return cmd_report(cfg, args)
    return 2


if __name__ == "__main__":
    sys.exit(main())
