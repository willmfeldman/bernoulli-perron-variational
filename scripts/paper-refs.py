_TOP_KEYS = {"format", "include", "exclude", "max_line", "papers", "bootstrap"}
_PAPER_KEYS = {"title", "arxiv", "version", "draft", "aux", "tex", "aliases", "snapshot", "decisions",
               "references", "latex", "prefixes"}
_DECISION_KEYS = {"reviewed", "retarget", "accept_moved"}
_LOCAL_KEYS = {"aux", "tex", "latex"}  # the only keys paper-refs/local.toml may set
DEFAULT_LATEX = ["latexmk", "-pdf", "-interaction=nonstopmode", "-halt-on-error"]
_BOOT_KEYS = {"exclude", "external", "bare_equations", "exempt", "cited_default", "cited_files"}


class Config:
    def __init__(self, root: str, data: dict):
        self.root = root
        self.data = data
        if data.get("format", 1) != 1:
            die(f"{CONFIG_REL}: unsupported format {data.get('format')!r}")
        for k in data:
            if k not in _TOP_KEYS:
                die(f"{CONFIG_REL}: unknown key {k!r}")
        self.include = list(data.get("include", DEFAULT_INCLUDE))
        self.exclude = list(data.get("exclude", []))
        self.max_line = int(data.get("max_line", DEFAULT_MAX_LINE))
        self.papers: dict[str, dict] = {}
        for key, p in sorted((data.get("papers") or {}).items()):
            if not re.fullmatch(KEY, key):
                die(f"{CONFIG_REL}: invalid paper key {key!r}")
            if "version" not in p:
                die(f"{CONFIG_REL}: papers.{key}: 'version' is required")
            for k in p:
                if k not in _PAPER_KEYS:
                    die(f"{CONFIG_REL}: papers.{key}: unknown key {k!r}")
            for scope, d in (p.get("decisions") or {}).items():
                where = f"{CONFIG_REL}: papers.{key}.decisions.{scope!r}"
                if not re.fullmatch(r"[^>\s]+->[^>\s]+", scope):
                    die(f"{where}: the scope is \"<from version>-><to version>\"")
                if not isinstance(d, dict) or set(d) - _DECISION_KEYS:
                    die(f"{where}: allowed keys are {sorted(_DECISION_KEYS)}")
                if not d.get("reviewed"):
                    die(f"{where}: 'reviewed' (the to-snapshot's source commit, e-print or aux:<sha>) is required")
                if not isinstance(d.get("retarget", {}), dict) or not isinstance(d.get("accept_moved", []), list):
                    die(f"{where}: 'retarget' is a table and 'accept_moved' a list")
            if not isinstance(p.get("references", {}), dict):
                die(f"{CONFIG_REL}: papers.{key}.references: {{ \"<version>\" = \"<snapshot path>\" }}")
            self.papers[key] = p
        boot = data.get("bootstrap") or {}
        for k in boot:
            if k not in _BOOT_KEYS:
                die(f"{CONFIG_REL}: bootstrap: unknown key {k!r}")
        self.boot_exclude = list(boot.get("exclude", []))
        self.boot_external = list(boot.get("external", []))
        self.boot_bare_equations = bool(boot.get("bare_equations", True))
        self.boot_cited_default = boot.get("cited_default")
        self.boot_cited_files = []
        for ver, globs in sorted((boot.get("cited_files") or {}).items()):
            if not isinstance(globs, list):
                die(f"{CONFIG_REL}: bootstrap.cited_files: {{ \"<version>\" = [\"<glob>\", ...] }}")
            self.boot_cited_files += [(glob_re(g), str(ver)) for g in globs]
        self.boot_exempt = []
        for ex in boot.get("exempt", []):
            if not isinstance(ex, dict) or set(ex) - {"file", "text", "other_work"} or "text" not in ex:
                die(f"{CONFIG_REL}: bootstrap.exempt entries are "
                    f"{{ file = \"glob\", text = \"...\", other_work = true|false }}")
            self.boot_exempt.append((glob_re(ex.get("file", "**")), ex["text"], bool(ex.get("other_work"))))
        if not self.papers:
            die(f"{CONFIG_REL}: no [papers.<KEY>] table")

    def reference_paths(self, key: str) -> dict[str, str]:
        return {str(v): os.path.join(self.root, p) for v, p in sorted((self.papers[key].get("references") or {}).items())}

    def snapshot_path(self, key: str) -> str:
        rel = self.papers[key].get("snapshot", f"paper-refs/{key}.json")
        return os.path.join(self.root, rel)

    def paths(self, key: str, field: str) -> list[str]:
        v = self.papers[key].get(field)
        if not v:
            return []
        vs = [v] if isinstance(v, str) else list(v)
        return [os.path.normpath(os.path.join(self.root, x)) for x in vs]


def load_config(root: str) -> Config:
    path = os.path.join(root, CONFIG_REL)
    if not os.path.exists(path):
        die(f"no {CONFIG_REL} under {root}")
    if tomllib is None:
        die("Python 3.11+ is required (tomllib)")
    with open(path, "rb") as fh:
        try:
            data = tomllib.load(fh)
        except tomllib.TOMLDecodeError as e:
            die(f"{CONFIG_REL}: {e}")
    local = os.path.join(root, LOCAL_REL)
    if os.path.exists(local):
        merge_local(data, local)
    return Config(root, data)


def merge_local(data: dict, path: str) -> None:
    """Merge the dev-only source paths of ``paper-refs/local.toml`` into the config. It may set
    only aux, tex and latex, for papers that config.toml defines, and never a key config.toml
    sets already."""
    with open(path, "rb") as fh:
        try:
            local = tomllib.load(fh)
        except tomllib.TOMLDecodeError as e:
            die(f"{LOCAL_REL}: {e}")
    if set(local) - {"papers"}:
        die(f"{LOCAL_REL}: only [papers.<KEY>] tables are allowed")
    papers = data.get("papers") or {}
    for key, p in (local.get("papers") or {}).items():
        if key not in papers:
            die(f"{LOCAL_REL}: papers.{key} is not in {CONFIG_REL}")
        if not isinstance(p, dict) or set(p) - _LOCAL_KEYS:
            die(f"{LOCAL_REL}: papers.{key}: allowed keys are {sorted(_LOCAL_KEYS)}")
        for k, v in p.items():
            if k in papers[key]:
                die(f"{LOCAL_REL}: papers.{key}.{k} is also set in {CONFIG_REL}; set it in one place")
            papers[key][k] = v


def iter_files(cfg: Config, extra_exclude: list[str] = ()) -> list[str]:
    inc = [glob_re(p) for p in cfg.include]
    exc = [glob_re(p) for p in list(cfg.exclude) + list(extra_exclude)]
    out = []
    for dirpath, dirnames, filenames in os.walk(cfg.root):
        dirnames[:] = sorted(d for d in dirnames if d not in ALWAYS_SKIP_DIRS)
        for f in filenames:
            rel = os.path.relpath(os.path.join(dirpath, f), cfg.root).replace(os.sep, "/")
            if any(r.match(rel) for r in inc) and not any(r.match(rel) for r in exc):
                out.append(rel)
    return sorted(out)


# --------------------------------------------------------------------------- .aux parsing


def read_group(s: str, i: int) -> tuple[str, int] | None:
    """Balanced ``{...}`` starting at s[i]; returns (contents, index after)."""
    if i >= len(s) or s[i] != "{":
        return None
    depth, j = 0, i
    while j < len(s):
        c = s[j]
        if c == "\\":
            j += 2
            continue
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                return s[i + 1 : j], j + 1
        j += 1
    return None


def split_groups(s: str) -> list[str] | None:
    """``{a}{b}{c}`` -> [a, b, c]; None if ``s`` is not a sequence of groups."""
    out, i = [], 0
    s = s.strip()
    while i < len(s):
        if s[i].isspace():
            i += 1
            continue
        g = read_group(s, i)
        if g is None:
            return None
        out.append(g[0])
        i = g[1]
    return out


_NUMBER_MACROS = r"protect|relax|textup|textrm|textnormal|textbf|textit|textsf|emph|upshape|normalfont|" \
    r"itshape|bfseries|rmfamily|text|mathrm|mathbf|ignorespaces|@empty|nobreak|ensuremath"


def clean_number(s: str) -> str | None:
    """De-TeX a label number; None if it still contains a macro that is not formatting
    (e.g. a protected ``\\Roman{section}`` would otherwise become the word "section")."""
    t = re.sub(rf"\\(?:{_NUMBER_MACROS})(?![A-Za-z@])\s*", "", s)
    if re.search(r"\\[A-Za-z@]", t):
        return None
    t = t.replace("{", "").replace("}", "").replace("~", " ").replace("\\ ", " ")
    return re.sub(r"\s+", " ", t).strip()


def clean_tex(s: str) -> str:
    s = re.sub(r"\\(?:protect|relax|textup|textrm|textnormal|upshape|normalfont|text|mathrm|ignorespaces|@empty)\b\s*", "", s)
    s = re.sub(r"\\[A-Za-z@]+\s*", "", s)
    s = s.replace("{", "").replace("}", "").replace("~", " ")
    return re.sub(r"\s+", " ", s).strip()


def read_aux_tree(paths: list[str]) -> tuple[list[tuple[str, list[str]]], str]:
    """All ``\\newlabel`` entries of the given aux files and their ``\\@input`` children,
    in reading order, plus a hash of all files read."""
    entries: list[tuple[str, list[str]]] = []
    h = hashlib.sha256()
    active: list[str] = []  # files being read: guards against \\@input cycles only

    def visit(path: str) -> None:
        real = os.path.realpath(path)
        if real in active:
            die(f"aux \\@input cycle: {' -> '.join(active + [real])}")
        if not os.path.exists(path):
            die(f"aux file not found: {path}")
        active.append(real)
        text = read_text(path)
        h.update(os.path.basename(path).encode() + b"\0" + text.encode() + b"\0")
        i = 0
        tok = re.compile(r"\\newlabel\{|\\@input\{")
        while True:
            m = tok.search(text, i)
            if not m:
                break
            g = read_group(text, m.end() - 1)
            if g is None:
                i = m.end()
                continue
            name, j = g
            if m.group(0) == "\\@input{":
                visit(os.path.join(os.path.dirname(path), name))
                i = j
                continue
            v = read_group(text, j)
            if v is None:
                i = j
                continue
            fields = split_groups(v[0])
            entries.append((name, fields if fields is not None else []))
            i = v[1]
        active.pop()

    for p in paths:
        visit(p)
    return entries, h.hexdigest()


def parse_cref_type(field0: str) -> str | None:
    m = re.match(r"\s*\[([^\]]*)\]", field0)
    return m.group(1) if m else None


