def apply_edits(text: str, edits: list[tuple[int, int, str]]) -> str:
    out, last = [], 0
    for s, e, new in sorted(edits):
        out.append(text[last:s])
        out.append(new)
        last = e
    out.append(text[last:])
    return "".join(out)


def rewrap(rel: str, old: str, new: str, limit: int, probs: list[Problem]) -> str:
    """Wrap lines of ``new`` that changed and now exceed ``limit``."""
    if not rel.endswith(".lean") or limit <= 0 or old == new:
        return new
    old_lines = set(old.split("\n"))
    lines = new.split("\n")
    regions = comment_regions(new)
    starts, pos = [], 0
    for ln in lines:
        starts.append(pos)
        pos += len(ln) + 1
    def region_of(idx: int):
        ls, le = starts[idx], starts[idx] + len(lines[idx])
        return next((r for r in regions if r[0] < le and r[1] > ls and r[0] - ls < limit), None)

    out: list[str] = []
    carry = None  # (wrapped-off tail, region) waiting to flow into the next line
    for idx, ln in enumerate(lines):
        changed = ln not in old_lines
        if carry is not None:
            tail, creg = carry
            carry = None
            merged = _merge_into(tail, ln, creg[2]) if region_of(idx) == creg else None
            if merged is None:
                out.append(tail)
            else:
                ln, changed = merged, True
        if not changed or len(ln) <= limit or LINE_LIMIT_SKIP in ln:
            out.append(ln)
            continue
        reg = region_of(idx)
        nxt = lines[idx + 1] if idx + 1 < len(lines) else None
        w = wrap_line(ln, reg[2], limit, nxt) if reg is not None else None
        if w is None:
            out.append(ln)
        else:
            out.extend(w[:-1])
            carry = (w[-1], reg)
    if carry is not None:
        out.append(carry[0])
    for n, ln in enumerate(out, 1):  # validate every line the rewrite produced
        if ln not in old_lines and len(ln) > limit and LINE_LIMIT_SKIP not in ln:
            probs.append(Problem(rel, n, "error", "long-line",
                                 f"line is {len(ln)} columns after the rewrite (limit {limit}); wrap it by hand"))
    return "\n".join(out)


_LIST_MARK = re.compile(r"^(?:[-*+]|\d+[.)])\s")


def _merge_into(tail: str, nxt: str, kind: str) -> str | None:
    """Flow a wrapped-off ``tail`` into the next line of the same paragraph, or None."""
    if tail.endswith(("  ", "\\")) or not nxt.strip():
        return None
    t_ind = len(tail) - len(tail.lstrip())
    if kind == "line":
        mt = re.match(r"(\s*--\s?)", tail)
        mn = re.match(r"(\s*)--\s?(.*)$", nxt)
        if not mt or not mn or len(mn.group(1)) != len(tail) - len(tail.lstrip()):
            return None
        body = mn.group(2).strip()
        if not body or MD_LINE_START.match(body) or _LIST_MARK.match(body) or body.startswith("-"):
            return None
        return tail.rstrip() + " " + body
    body = nxt.strip()
    if len(nxt) - len(nxt.lstrip()) != t_ind:
        return None
    if MD_LINE_START.match(body) or _LIST_MARK.match(body) or body.startswith(("/-", "-/")):
        return None
    if "-/" in body and not body.endswith("-/"):
        return None
    return tail.rstrip() + " " + body


def drop_unwrappable(rel: str, text: str, edits: list, limit: int, probs: list[Problem]) -> list:
    """Keep, line by line and left to right, the edits that still let the line fit within ``limit``
    or be wrapped; the rest stay plain (Markdown headings and table rows cannot wrap) and are
    reported. Greedy and left to right, so a rerun reaches the same result."""
    if not rel.endswith(".lean") or limit <= 0:
        return edits
    regions = comment_regions(text)
    by_line: dict[int, list] = {}
    for ed in sorted(edits):
        by_line.setdefault(line_of(text, ed[0]), []).append(ed)
    keep = []
    for ln, eds in sorted(by_line.items()):
        ls = text.rfind("\n", 0, eds[0][0]) + 1
        le = text.find("\n", eds[0][0])
        le = len(text) if le < 0 else le
        reg = next((r for r in regions if r[0] <= eds[0][0] <= r[1]), None)
        chosen, dropped = [], 0
        for ed in eds:
            trial = chosen + [ed]
            new_line = apply_edits(text[ls:le], [(a - ls, b - ls, n) for a, b, n in trial])
            if len(new_line) <= limit or LINE_LIMIT_SKIP in new_line or \
                    (reg is not None and wrap_line(new_line, reg[2], limit, None) is not None):
                chosen = trial
            else:
                dropped += 1
        if dropped:
            probs.append(Problem(rel, ln, "warning", "kept-plain",
                                 f"{dropped} citation(s) left plain: with links the line would exceed {limit} "
                                 "columns and cannot be wrapped (heading or table row)"))
        keep.extend(chosen)
    return keep


