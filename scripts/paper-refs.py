#!/usr/bin/env python3
# canonical-paper-refs v0.3.1
"""Keep paper citations in Lean comments and docstrings in step with the paper.

A citation is a Markdown link whose target names a paper key and a LaTeX label:

    [Lemma 2.12](#MAIN:lem:stability)
    [Theorem 1.1(i)](#MAIN:item:first)      (label of an enumerate item)
    Lemmas [2.3](#MAIN:lem:a) and [2.4](#MAIN:lem:b)
    [(3.4)](#MAIN:eq:energy)

The link text is what readers see in the editor, in hovers and in generated
documentation. The target ``#KEY:label`` is deliberately inert (no page has
that id): it only carries the key. ``sync`` rewrites the number (and, if the
label changed kind, the kind word) in the link text from a label snapshot;
nothing else in the text changes.

A label is not trusted blindly: when a new paper revision changes what a cited
label means (its kind, title, alias group or item parent changed, or it was
removed), ``snapshot``, ``sync`` and ``check`` stop until the config records a
decision for that transition, reviewed against that source:
``[papers.KEY.decisions."v1->v2"]`` with ``reviewed``, ``retarget`` and
``accept_moved``. Decisions never carry over to a later transition or source.

Files (relative to the repository root):

  paper-refs/config.toml   papers, versions, decisions, optional source paths
  paper-refs/local.toml    optional, dev-only source paths (aux, tex, latex) per paper;
                           strip it at export so the shipped config names no local paths
  paper-refs/<KEY>.json    normalized label snapshot, generated by ``snapshot``

Commands (run from the repository root, or pass --root):

  paper-refs.py snapshot [KEY] [--aux F ...] [--tex F ...] [--frozen REF | --eprint ID]
                         [--out PATH --as-version V]
        read LaTeX .aux file(s) and the .tex source (theorem kinds, item
        parents, aliases) and write paper-refs/<KEY>.json; --frozen exports
        the tagged paper commit, compiles it with latexmk and snapshots that;
        --out/--as-version write a reference snapshot of another version
  paper-refs.py sync
        rewrite displayed numbers and kind words from the snapshots; stops
        before writing anything on a snapshot, config or identity error
  paper-refs.py check [--release] [--strict]
        non-zero exit on unknown keys or labels, stale numbers or kinds, cited
        labels that moved without a decision, or a bad snapshot or config;
        --release also requires a compiled frozen (or matching e-print),
        non-draft snapshot and no README or metadata naming another version;
        --strict also fails on plain-text citations of the paper (with
        --release, only exemptions for other works are honoured)
  paper-refs.py suggest [--paper KEY] [--cited VERSION] [--json] [--manifest]
        list plain-text citations ("Proposition 3.8", "(3.4)") in comments and
        how each resolves in the version it follows (main or reference
        snapshot); unmarked citations whose number means different things in
        different versions are needs-review
  paper-refs.py bootstrap --write --cited VERSION [--paper KEY]
        convert the uniquely resolved citations (needs-review ones only after a
        reviewed decision in paper-refs/bootstrap-<KEY>-reviewed.tsv); writes a
        review manifest paper-refs/bootstrap-<KEY>-<VERSION>.tsv
  paper-refs.py report [--all] [--json]
        coverage table: which labels the Lean sources cite, and where

Only comments (``--``, ``/- -/``, ``/-- -/``, ``/-! -/``) of ``.lean`` files are
read or changed, plus whole ``.md`` files listed in ``include``. Python 3.11+
standard library only (git and latexmk for --frozen); output is deterministic and
every command is idempotent.
"""

