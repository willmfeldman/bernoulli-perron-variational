def canon_kind(name: str | None) -> str | None:
    if not name:
        return None
    n = name.strip().rstrip("*")
    if n in _KIND_ALIASES:
        return _KIND_ALIASES[n]
    low = n.lower()
    return _KIND_ALIASES.get(low, low)


def kind_display(kind: str, like: str = "") -> str:
    """Display word for a kind, following the capitalisation of ``like``."""
    word = {"equation": "equation"}.get(kind, kind.capitalize())
    if like and like[0].islower():
        word = word.lower()
    elif like and like[0].isupper():
        word = word[0].upper() + word[1:]
    return word


def kind_compatible(word_kind: str | None, label_kind: str | None) -> bool:
    if word_kind is None or label_kind is None:
        return True
    if word_kind == label_kind:
        return True
    return word_kind in SECTION_FAMILY and label_kind in SECTION_FAMILY


def word_kind(word: str) -> str | None:
    return KIND_WORDS.get(word.lower().rstrip("."))


