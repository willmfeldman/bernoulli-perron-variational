class Problem:
    __slots__ = ("path", "line", "level", "code", "msg")

    def __init__(self, path, line, level, code, msg):
        self.path, self.line, self.level, self.code, self.msg = path, line, level, code, msg

    def render(self) -> str:
        loc = f"{self.path}:{self.line}" if self.line else f"{self.path}"
        return f"{loc}: {self.level}: [{self.code}] {self.msg}"

    def annotate(self) -> str:
        kind = "error" if self.level == "error" else "warning"
        line = f",line={self.line}" if self.line else ""
        return f"::{kind} file={self.path}{line}::[{self.code}] {self.msg}"


def emit(problems: list[Problem]) -> None:
    gha = os.environ.get("GITHUB_ACTIONS") == "true"
    for p in sorted(problems, key=lambda p: (p.path, p.line or 0, p.code, p.msg)):
        print(p.render())
        if gha:
            print(p.annotate())


def die(msg: str) -> None:
    print(f"{TOOL}: error: {msg}", file=sys.stderr)
    sys.exit(2)


def glob_re(pattern: str) -> re.Pattern:
    out, i = "", 0
    while i < len(pattern):
        if pattern.startswith("**/", i):
            out += "(?:.*/)?"
            i += 3
        elif pattern.startswith("**", i):
            out += ".*"
            i += 2
        elif pattern[i] == "*":
            out += "[^/]*"
            i += 1
        elif pattern[i] == "?":
            out += "[^/]"
            i += 1
        else:
            out += re.escape(pattern[i])
            i += 1
    return re.compile(out + r"\Z")


def line_of(text: str, pos: int) -> int:
    return text.count("\n", 0, pos) + 1


def read_text(path: str) -> str:
    with open(path, encoding="utf-8", newline="") as fh:
        return fh.read()


def write_text(path: str, text: str) -> None:
    with open(path, "w", encoding="utf-8", newline="") as fh:
        fh.write(text)


